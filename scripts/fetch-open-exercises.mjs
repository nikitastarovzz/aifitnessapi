#!/usr/bin/env node
/**
 * Open exercises: every exercise in free-exercise-db (yuhonas/free-exercise-db,
 * released into the public domain under the Unlicense), read at a pinned
 * commit, normalized, and joined to this site's exercise taxonomy crosswalk for
 * the HealthKit and Health Connect types it already matched.
 *
 *   NODE_USE_ENV_PROXY=1 node scripts/fetch-open-exercises.mjs [--offline]
 *     --offline reparses .cache/open-exercises at the commit meta.json names.
 *   Then `npm run datasets` (public/datasets/open-exercises-2026.{json,csv,md}).
 *
 * Reads:
 *   `git ls-remote https://github.com/yuhonas/free-exercise-db HEAD`: the
 *     commit to read. Every file below is fetched from raw.githubusercontent.com
 *     at that commit, never at `main`, so a row's image URLs keep resolving to
 *     the bytes this run saw.
 *   dist/exercises.json: the exercises.
 *   LICENSE.md: the Unlicense; its full text ships with the dataset.
 *   README.md: the line that says image paths are relative to exercises/, and
 *     the line that names the project it restructured (wrkout/exercises.json).
 *   wrkout/exercises.json LICENSE.md, at its own `git ls-remote` HEAD: the
 *     upstream project's license, so the provenance claim is checked too.
 *   src/data/exerciseTaxonomy.ts (generated by scripts/fetch-exercise-taxonomy.mjs):
 *     ET_EXERCISE_MATCHES (free-exercise-db exercise names with the same key as
 *     a HealthKit or Health Connect constant) and the mapped free-exercise-db
 *     categories in ET_TERMS. Nothing is matched here: a row carries a type only
 *     where that crosswalk already has one, by exercise name first and by
 *     category otherwise, and every other row is null.
 *
 * A short parse fails: fewer than EXPECTED_MIN exercises, a duplicate id, an
 * exercise without its fields, a license or README line that moved, or a
 * crosswalk row whose exercise is gone or renamed upstream (regenerate the
 * taxonomy first) all exit non-zero before anything is written.
 *
 * Writes src/data/openExercises.ts.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const CACHE = ".cache/open-exercises";
const META = join(CACHE, "meta.json");
const OUT = "src/data/openExercises.ts";
const ET_REL = "src/data/exerciseTaxonomy.ts";
const OFFLINE = process.argv.includes("--offline");
const RAW = "https://raw.githubusercontent.com";
const REPO = "yuhonas/free-exercise-db";
const UPSTREAM = "wrkout/exercises.json";

/** free-exercise-db held 876 exercises on 2026-11-24 (commit f00c92c). */
export const EXPECTED_MIN = 876;
/** Joins instruction steps in the CSV-safe string column. No step may contain it. */
export const STEP_SEPARATOR = " | ";

const sha256 = (s) => createHash("sha256").update(s).digest("hex");
const fail = (m) => {
  console.error(`\n✗ fetch-open-exercises: ${m}\n`);
  process.exit(1);
};

function lsRemote(repo) {
  const out = execFileSync("git", ["ls-remote", `https://github.com/${repo}`, "HEAD"], { encoding: "utf8", timeout: 60_000 });
  const sha = out.split(/\s+/)[0];
  if (!/^[0-9a-f]{40}$/.test(sha ?? "")) fail(`git ls-remote returned no HEAD for ${repo}`);
  return sha;
}

async function fetchText(url) {
  let lastErr;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(url, { headers: { "User-Agent": "aifitnessapi-generator (+https://aifitnessapi.com)" } });
      if (!res.ok) throw new Error(`${res.status} for ${url}`);
      return await res.text();
    } catch (e) {
      lastErr = e;
      await new Promise((r) => setTimeout(r, 1000 * (attempt + 1)));
    }
  }
  fail(`could not read ${url}: ${lastErr?.message}`);
}

/* ── pure helpers (exported for scripts/open-exercises.test.mjs) ─────────── */

export const rawUrl = (repo, commit, path) => `${RAW}/${repo}/${commit}/${path}`;
export const imageUrl = (commit, path) => rawUrl(REPO, commit, `exercises/${path}`);
export const sourceUrl = (commit, id) => `https://github.com/${REPO}/blob/${commit}/exercises/${id}.json`;

/** One upstream exercise, normalized; `cross` is { exercise: Map, category: Map } from the crosswalk. */
export function normalize(e, commit, cross) {
  for (const k of ["id", "name", "category", "level"]) {
    if (typeof e[k] !== "string" || !e[k]) fail(`exercise ${JSON.stringify(e.id)} has no ${k}`);
  }
  for (const k of ["primaryMuscles", "secondaryMuscles", "instructions", "images"]) {
    if (!Array.isArray(e[k]) || e[k].some((x) => typeof x !== "string")) fail(`exercise ${e.id}: ${k} is not a list of strings`);
  }
  for (const s of e.instructions) if (s.includes(STEP_SEPARATOR.trim())) fail(`exercise ${e.id}: a step contains "${STEP_SEPARATOR.trim()}", the dataset's step separator`);
  const byName = cross.exercise.get(e.id);
  const byCategory = cross.category.get(e.category);
  const hit = byName ?? byCategory ?? null;
  return {
    id: e.id,
    name: e.name,
    category: e.category,
    equipment: e.equipment ?? null,
    level: e.level,
    mechanic: e.mechanic ?? null,
    force: e.force ?? null,
    primaryMuscles: e.primaryMuscles,
    secondaryMuscles: e.secondaryMuscles,
    instructions: e.instructions,
    images: e.images.map((p) => imageUrl(commit, p)),
    source: sourceUrl(commit, e.id),
    healthkit: hit?.healthkit ?? [],
    healthConnect: hit?.healthConnect ?? [],
    hcSegment: hit?.hcSegment ?? [],
    crosswalkBasis: byName ? "exercise-name" : byCategory ? "category" : null,
  };
}

/** The crosswalk's free-exercise-db matches, by exercise id and by category. */
export function crosswalkFrom(etSrc) {
  const arr = (name) => {
    const m = new RegExp(`export const ${name}: [^=]+= `).exec(etSrc);
    if (!m) fail(`${ET_REL} has no ${name}`);
    const open = m.index + m[0].length;
    const end = etSrc.indexOf("\n];", open);
    if (end < 0) fail(`${name} in ${ET_REL} does not close`);
    return JSON.parse(etSrc.slice(open, end + 2));
  };
  const fetchedOn = (etSrc.match(/export const ET_FETCHED_ON = "([^"]+)"/) ?? [])[1];
  if (!fetchedOn) fail(`no ET_FETCHED_ON in ${ET_REL}`);
  const exercise = new Map();
  const names = new Map();
  for (const m of arr("ET_EXERCISE_MATCHES")) {
    if (m.database !== "free-exercise-db") continue;
    exercise.set(m.exerciseId, { healthkit: m.healthkit, healthConnect: m.healthConnect, hcSegment: m.hcSegment });
    names.set(m.exerciseId, m.name);
  }
  const category = new Map();
  for (const t of arr("ET_TERMS")) {
    if (t.database !== "free-exercise-db" || t.facet !== "category" || t.status !== "mapped") continue;
    category.set(t.term, { healthkit: t.healthkit.exact, healthConnect: t.healthConnect.exact, hcSegment: t.hcSegment.exact });
  }
  return { exercise, category, names, fetchedOn };
}

/* ── run ─────────────────────────────────────────────────────────────────── */

async function main() {
  mkdirSync(CACHE, { recursive: true });
  const meta = existsSync(META) ? JSON.parse(readFileSync(META, "utf8")) : {};
  let commit = meta.commit;
  let upstreamCommit = meta.upstreamCommit;
  if (!OFFLINE) {
    commit = lsRemote(REPO);
    upstreamCommit = lsRemote(UPSTREAM);
  }
  if (!commit || !upstreamCommit) fail(`offline and ${META} names no commit`);

  const files = {
    exercises: { repo: REPO, commit, path: "dist/exercises.json" },
    license: { repo: REPO, commit, path: "LICENSE.md" },
    readme: { repo: REPO, commit, path: "README.md" },
    upstreamLicense: { repo: UPSTREAM, commit: upstreamCommit, path: "LICENSE.md" },
  };
  const text = {};
  const read = {};
  for (const [k, f] of Object.entries(files)) {
    const file = join(CACHE, `${f.repo.replace("/", "__")}@${f.commit}__${f.path.replace(/\//g, "__")}`);
    const url = rawUrl(f.repo, f.commit, f.path);
    if (existsSync(file)) {
      text[k] = readFileSync(file, "utf8");
    } else {
      if (OFFLINE) fail(`offline and ${file} is not cached`);
      text[k] = await fetchText(url);
      writeFileSync(file, text[k]);
      meta.reads = { ...(meta.reads ?? {}), [k]: { url, fetchedOn: new Date().toISOString().slice(0, 10) } };
    }
    const r = meta.reads?.[k];
    if (!r || r.url !== url) fail(`${META} has no read date for ${url}; delete ${CACHE} and run online`);
    read[k] = { url, fetchedOn: r.fetchedOn, sha256: sha256(text[k]) };
  }
  if (!OFFLINE) writeFileSync(META, JSON.stringify({ ...meta, commit, upstreamCommit }, null, 2));

  // License and provenance, each held to the line that states it.
  const licenseFirst = text.license.split("\n")[0].trim();
  if (licenseFirst !== "This is free and unencumbered software released into the public domain.") fail(`free-exercise-db LICENSE.md first line changed: ${licenseFirst}`);
  const anyPurpose = /for any purpose, commercial or non-commercial/.test(text.license.replace(/\s+/g, " "));
  if (!anyPurpose) fail("free-exercise-db LICENSE.md no longer says \"for any purpose, commercial or non-commercial\"");
  const imageLine = text.readme.split("\n").find((l) => l.includes(`prefix any of image path's contained in the \`JSON\` with \`https://raw.githubusercontent.com/${REPO}/main/exercises/\``));
  if (!imageLine) fail("free-exercise-db README no longer says image paths are relative to exercises/");
  const upstreamLine = text.readme.split("\n").find((l) => l.includes(`[exercises.json](https://github.com/${UPSTREAM})`));
  if (!upstreamLine) fail(`free-exercise-db README no longer names ${UPSTREAM}`);
  const upstreamFirst = text.upstreamLicense.split("\n")[0].trim();
  if (!/released into the public domain/.test(upstreamFirst)) fail(`${UPSTREAM} LICENSE.md first line changed: ${upstreamFirst}`);

  // Exercises.
  let raw;
  try {
    raw = JSON.parse(text.exercises);
  } catch (e) {
    fail(`dist/exercises.json is not JSON: ${e.message}`);
  }
  if (!Array.isArray(raw) || raw.length < EXPECTED_MIN) fail(`free-exercise-db: ${raw?.length} exercises, expected at least ${EXPECTED_MIN}`);
  const etSrc = readFileSync(ET_REL, "utf8");
  const cross = crosswalkFrom(etSrc);
  const byId = new Map(raw.map((e) => [e.id, e]));
  if (byId.size !== raw.length) fail("free-exercise-db: duplicate exercise ids");
  for (const [id, name] of cross.names) {
    const e = byId.get(id);
    if (!e) fail(`the crosswalk matched ${id}, which is no longer in free-exercise-db at ${commit}; regenerate ${ET_REL} first`);
    if (e.name !== name) fail(`the crosswalk matched "${name}" (${id}), which is now "${e.name}"; regenerate ${ET_REL} first`);
  }
  const rows = raw.map((e) => normalize(e, commit, cross)).sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const typed = rows.filter((r) => r.crosswalkBasis).length;

  const fetchedOn = Object.values(read).map((r) => r.fetchedOn).sort().at(-1);
  const sources = [
    { id: "exercises", title: "free-exercise-db dist/exercises.json", ...read.exercises, page: `https://github.com/${REPO}/blob/${commit}/dist/exercises.json` },
    { id: "license", title: "free-exercise-db LICENSE.md (the Unlicense)", ...read.license, page: `https://github.com/${REPO}/blob/${commit}/LICENSE.md` },
    { id: "readme", title: "free-exercise-db README.md", ...read.readme, page: `https://github.com/${REPO}/blob/${commit}/README.md` },
    { id: "upstream-license", title: "wrkout/exercises.json LICENSE.md", ...read.upstreamLicense, page: `https://github.com/${UPSTREAM}/blob/${upstreamCommit}/LICENSE.md` },
    { id: "crosswalk", title: "This site's exercise taxonomy crosswalk (src/data/exerciseTaxonomy.ts)", url: null, fetchedOn: cross.fetchedOn, sha256: sha256(etSrc), page: "/tools/exercise-taxonomy-crosswalk" },
  ];

  const j = (v) => JSON.stringify(v);
  const out = `/**
 * Open exercises: every exercise in free-exercise-db at one pinned commit,
 * normalized, with the HealthKit and Health Connect types this site's
 * exercise taxonomy crosswalk already matched.
 *
 * GENERATED — do not hand-edit; regenerate with NODE_USE_ENV_PROXY=1 node scripts/fetch-open-exercises.mjs
 *
 * Sources:
${sources.map((s) => ` *   ${s.title}: ${s.page} — read ${s.fetchedOn}`).join("\n")}
 *
 * Copied verbatim: id, name, category, equipment, level, mechanic, force, the
 * muscle lists, every instruction step and every image path (made absolute at
 * the pinned commit), and the license text.
 * From the crosswalk, not matched here: healthkit, healthConnect, hcSegment,
 * crosswalkBasis (see OE_CROSSWALK_RULE).
 */

export const OE_FETCHED_ON = ${j(fetchedOn)};
export const OE_REPO = ${j(`https://github.com/${REPO}`)};
/** The free-exercise-db commit every file and image URL is pinned to. */
export const OE_COMMIT = ${j(commit)};
export const OE_COUNT = ${rows.length};
export const OE_TYPED_COUNT = ${typed};

/** free-exercise-db's LICENSE.md at OE_COMMIT, whole. */
export const OE_LICENSE_TEXT = ${j(text.license.trimEnd())};
export const OE_LICENSE_FIRST_LINE = ${j(licenseFirst)};
/** The README line that says image paths are relative to exercises/ (it names main; this file pins the commit instead). */
export const OE_IMAGE_PATH_QUOTE = ${j(imageLine.trim())};
/** The README line that names the project free-exercise-db restructured, and that project's license line. */
export const OE_PROVENANCE = ${j({ quote: upstreamLine.trim(), upstream: `https://github.com/${UPSTREAM}`, upstreamCommit, upstreamLicenseFirstLine: upstreamFirst })};

export const OE_CROSSWALK_RULE = ${j(
    `healthkit, healthConnect and hcSegment are copied from this site's exercise taxonomy crosswalk (read ${cross.fetchedOn}), never matched here: from its exercise-name row when the crosswalk matched the exercise's own name to a constant (crosswalkBasis "exercise-name"), otherwise from its category row when the exercise's category has the same name as a constant (crosswalkBasis "category"), otherwise empty (crosswalkBasis null). The crosswalk matches by normalized name only, never by meaning.`,
  )};

export type OeSource = { id: string; title: string; url: string | null; page: string; fetchedOn: string; sha256: string };
export const OE_SOURCES: OeSource[] = ${JSON.stringify(sources, null, 2)};

export type OpenExercise = {
  id: string;
  name: string;
  category: string;
  equipment: string | null;
  level: string;
  mechanic: string | null;
  force: string | null;
  primaryMuscles: string[];
  secondaryMuscles: string[];
  instructions: string[];
  /** Absolute raw.githubusercontent.com URLs at OE_COMMIT. */
  images: string[];
  /** The exercise's own JSON file on GitHub at OE_COMMIT. */
  source: string;
  healthkit: string[];
  healthConnect: string[];
  hcSegment: string[];
  crosswalkBasis: "exercise-name" | "category" | null;
};
export const OE_EXERCISES: OpenExercise[] = [
${rows.map((r) => `  ${j(r)}`).join(",\n")}
];
`;
  writeFileSync(OUT, out);
  console.log(`fetch-open-exercises: ${rows.length} exercises at ${commit.slice(0, 7)}, ${typed} with a crosswalk type → ${OUT}`);
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
