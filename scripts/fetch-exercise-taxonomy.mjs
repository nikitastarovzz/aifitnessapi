async function read(id) {
  const src = SOURCES[id];
  const file = join(CACHE, `${id}.txt`);
  if (existsSync(file)) return readFileSync(file, "utf8");
  if (OFFLINE) fail(`offline and ${file} is not cached`);
  let lastErr;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(src.url, { headers: { "User-Agent": "aifitnessapi-generator (+https://aifitnessapi.com)", Accept: "application/json, text/plain;q=0.9, */*;q=0.5" } });
      if (!res.ok) throw new Error(`${res.status} for ${src.url}`);
      const text = await res.text();
      if (src.json) JSON.parse(text);
      writeFileSync(file, text);
      meta[id] = { url: src.url, fetchedOn: new Date().toISOString().slice(0, 10), sha256: sha256(text), via: "direct" };
      writeFileSync(META, JSON.stringify(meta, null, 2));
      return text;
    } catch (e) {
      lastErr = e;
      await new Promise((r) => setTimeout(r, 1000 * (attempt + 1)));
    }
  }
  fail(`could not read ${id} (${src.url}): ${lastErr?.message}`);
}

/** A JSON array literal exported from a generated TS module. */
function exportedArray(src, name) {
  const at = src.indexOf(`export const ${name}`);
  if (at < 0) fail(`${WT_REL} has no ${name}`);
  const open = src.indexOf("[", src.indexOf("=", at));
  let depth = 0;
  let inStr = false;
  let esc = false;
  for (let i = open; i < src.length; i++) {
    const c = src[i];
    if (inStr) {
      if (esc) esc = false;
      else if (c === "\\") esc = true;
      else if (c === '"') inStr = false;
      continue;
    }
    if (c === '"') inStr = true;
    else if (c === "[") depth++;
    else if (c === "]" && --depth === 0) return JSON.parse(src.slice(open, i + 1));
  }
  fail(`${name} in ${WT_REL} does not close`);
}

/* ── matching (exported for scripts/exercise-taxonomy.test.mjs) ──────────── */

export const key = (name) =>
  name
    .replace(/^EXERCISE_(SEGMENT_)?TYPE_/, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");

/** A constant's words: camelCase and SNAKE_CASE split, prefix removed. */
export const constantWords = (name) =>
  name
    .replace(/^EXERCISE_(SEGMENT_)?TYPE_/, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter(Boolean);

export const termWords = (term) => term.toLowerCase().split(/[^a-z0-9]+/).filter(Boolean);

/** Constants whose words contain the term's words as a contiguous run. */
export function nameContains(term, constants) {
  const w = termWords(term);
  if (!w.length) return [];
  return constants.filter((c) => {
    const cw = constantWords(c);
    for (let i = 0; i + w.length <= cw.length; i++) if (w.every((x, j) => cw[i + j] === x)) return true;
    return false;
  });
}

export function matchTerm(names, constants, matchable) {
  const keys = new Set(names.map(key));
  const exact = matchable ? constants.filter((c) => keys.has(key(c))) : [];
  const contains = [...new Set(names.flatMap((n) => nameContains(n, constants)))].filter((c) => !exact.includes(c));
  return { exact, nameContains: contains };
}

