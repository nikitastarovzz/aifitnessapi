/**
 * Exercise taxonomy crosswalk: the categories, equipment, muscles and body
 * parts three open exercise databases publish, set against the workout types
 * of HealthKit and Health Connect (ops/AUDIENCE-30-2026-11-05.md item 27).
 *
 *   NODE_USE_ENV_PROXY=1 node scripts/fetch-exercise-taxonomy.mjs [--offline]
 *     --offline reparses .cache/exercise-taxonomy without fetching.
 *   Then `npm run datasets`.
 *
 * Reads:
 *   free-exercise-db (yuhonas/free-exercise-db on GitHub, Unlicense): schema.json
 *     (the category, equipment and muscle enums), dist/exercises.json (every
 *     exercise name) and LICENSE.md.
 *   wger (wger.de REST API v2): /exercisecategory/, /equipment/, /muscle/, and
 *     the project README's License section on GitHub.
 *   ExerciseDB v1 (oss.exercisedb.dev, the open v1 API): /api/v1/bodyparts,
 *     /api/v1/equipments, /api/v1/muscles; the docs' product description; the
 *     ExerciseDB/exercisedb-api repository's LICENSE.
 *   src/data/workoutTypes.ts (generated by scripts/fetch-workout-types.mjs):
 *     HKWorkoutActivityType cases, ExerciseSessionRecord.EXERCISE_TYPE_* and
 *     ExerciseSegment.EXERCISE_SEGMENT_TYPE_* constants.
 *
 * A cached file is reused, so delete .cache/exercise-taxonomy to re-read.
 * wger.de and oss.exercisedb.dev are blocked from the dev environment; there
 * the cache holds the bodies .github/workflows/source-snapshot.yml printed, and
 * meta.json says which run. On a GitHub runner they fetch directly.
 *
 * Matching is by name only, and only where a name can be an activity:
 *   - key(name): lowercased, a leading EXERCISE_TYPE_ / EXERCISE_SEGMENT_TYPE_
 *     removed, every character outside a-z0-9 removed (the same normalisation
 *     as the workout-types crosswalk);
 *   - a database CATEGORY or EXERCISE NAME is "mapped" to a constant only when
 *     the keys are identical. Nothing is joined by meaning: "strength" is not
 *     STRENGTH_TRAINING, "cardio" is not mixedCardio;
 *   - equipment, muscle and body-part terms name no activity, so they are
 *     never mapped. For every term the constants whose name contains the term
 *     as whole words are listed as `nameContains`, labelled as a text
 *     coincidence, not a mapping.
 *
 * A short parse fails: every list declares its row count (EXPECTED) and the
 * script exits non-zero rather than write a truncated crosswalk.
 *
 * Writes src/data/exerciseTaxonomy.ts and
 * ops/sources/evidence/tools-exercise-taxonomy-crosswalk.json (one verbatim
 * quote per term read from a snapshot host, so source-quotes.yml re-checks
 * them against the live API).
 */
