    terms.push({ database, facet, sourceId, term: name, dbId, alias, quote });

  const schema = JSON.parse(text["fedb-schema"]).properties;
  for (const v of schema.category.enum) push("free-exercise-db", "category", "fedb-schema", v, null, null, null);
  for (const v of schema.equipment.enum.filter((x) => x !== null)) push("free-exercise-db", "equipment", "fedb-schema", v, null, null, null);
  for (const v of schema.primaryMuscles.items[0].enum) push("free-exercise-db", "muscle", "fedb-schema", v, null, null, null);

