import { ACCESS_REPORTS, ACCESS_REPORTS_IMPORTED_ON, type AccessReport } from "@/data/accessReports";
import ShareRow from "@/components/ShareRow";
import {
  ACCEPT_LABEL,
  MEDIAN_MIN,
  OUTCOMES,
  REPO,
  REPO_URL,
  accessBadge,
  accessBadgeAlt,
  accessBadgePath,
  buildIssueUrl,
  shareText,
  shareUrl,
  summarize,
  vendorBySlug,
} from "@/lib/accessReportSubmission.mjs";
import { badgeAlt, badgeMarkdown } from "@/lib/statusBadges.mjs";
import { site } from "@/lib/site";

/**
 * "Access reports" on a vendor's English /integrate page (and on
 * /fix/garmin-api-approval): what developers who applied for the vendor's API
 * access say happened, one row per accepted GitHub issue, from
 * src/data/accessReports.ts (generated by scripts/import-access-reports.mjs).
 *
 * Every row links the public issue it came from. The counts and the median
 * are computed here from those rows and nothing else; the median appears only
 * once MEDIAN_MIN reports give a number of days. With no accepted report the
 * section says so and offers the prefilled issue: no figure is shown for it.
 * ClusterPage renders it on English pages only, never on a translation.
 *
 * Each row has a Share action (components/ShareRow, plain compose links) with
 * a line that describes the report, not the reader (shareText), and the
 * section ends with the vendor's README badge, public/badges/access/<vendor>.svg,
 * which the importer redraws from the same rows.
 */

const OUTCOME_LABEL: Record<AccessReport["outcome"], string> = {
  approved: "Approved",
  rejected: "Rejected",
  "no-answer": "No answer",
  pending: "Pending",
};
const linkCls = "font-medium text-brand-600 hover:text-brand-500";

export default function AccessReports({ vendor }: { vendor: string }) {
  const v = vendorBySlug(vendor);
  if (!v) return null;
  const reports = ACCESS_REPORTS.filter((r) => r.vendor === vendor).sort((a, b) => b.applied.localeCompare(a.applied) || b.issue - a.issue);
  const s = summarize(reports);
  const href = buildIssueUrl({ vendor });
  const days = (n: number) => `${n} ${n === 1 ? "day" : "days"}`;
  const badgePath = accessBadgePath(vendor);
  const badge = accessBadge(v.name, s);

  const button = (
    <a
      href={href}
      rel="noopener"
      data-cta={`access-report-${vendor}`}
      data-cta-source="access-reports"
      className="inline-flex min-h-[40px] items-center rounded-xl bg-brand-600 px-5 py-2.5 text-sm font-semibold text-white transition-colors hover:bg-brand-500"
    >
      Report your application
    </a>
  );

  return (
    <section
      id="access-reports"
      data-access-reports={vendor}
      className="mt-12 scroll-mt-24 rounded-2xl border border-[var(--border)] bg-[var(--surface)] p-5 sm:p-6"
    >
      <h2 className="text-lg font-bold tracking-tight text-[var(--fg)]">{`${v.name} API access: reports from developers`}</h2>
      <p className="mt-2 text-sm leading-relaxed text-[var(--muted)]">
        {`What developers who applied for ${v.name} API access say happened: the month they applied, the use, the outcome and the days to a first answer. ` +
          `Each report is a public GitHub issue in this site's repository (${REPO}), listed once a maintainer has read it and added the `}
        <code className="font-mono text-xs">{ACCEPT_LABEL}</code>
        {" label. A report is one submitter's account, not a figure from the vendor."}
      </p>

      {reports.length === 0 ? (
        <div data-access-reports-empty className="mt-5">
          <p className="text-sm font-semibold text-[var(--fg)]">{`No ${v.name} reports have been accepted yet.`}</p>
          <p className="mt-1 text-sm text-[var(--muted)]">
            {"If you have applied, the button opens a GitHub issue with the vendor filled in. Everything in it is public: leave out keys, emails and people's names."}
          </p>
          <div className="mt-4">{button}</div>
        </div>
      ) : (
        <div className="mt-5">
          <p data-access-reports-summary className="text-sm text-[var(--fg)]">
            {`${s.total} ${s.total === 1 ? "report" : "reports"}: ` +
              OUTCOMES.filter((o) => s.counts[o] > 0)
                .map((o) => `${s.counts[o]} ${OUTCOME_LABEL[o as AccessReport["outcome"]].toLowerCase()}`)
                .join(", ") +
              "."}
            {s.medianDays !== null
              ? ` Median time to a first answer: ${days(s.medianDays)}, across the ${s.withDays} reports that give one.`
              : ` A median time to a first answer is shown once ${MEDIAN_MIN} reports give one (${s.withDays} so far).`}
          </p>
          <div className="mt-3 overflow-x-auto">
            <table className="w-full min-w-[580px] text-left text-sm">
              <thead className="text-xs uppercase tracking-wider text-[var(--muted)]">
                <tr>
                  <th className="py-2 pr-3">Applied</th>
                  <th className="py-2 pr-3">Use</th>
                  <th className="py-2 pr-3">Outcome</th>
                  <th className="py-2 pr-3 text-right">Days to first answer</th>
                  <th className="py-2 pr-3">Report</th>
                  <th className="py-2">Share</th>
                </tr>
              </thead>
              <tbody>
                {reports.map((r) => (
                  <tr key={r.issue} data-access-report={r.issue} className="border-t border-[var(--border)] text-[var(--fg)]">
                    <td className="py-2 pr-3 font-mono text-xs">{r.applied}</td>
                    <td className="py-2 pr-3">{r.use}</td>
                    <td className="py-2 pr-3">{OUTCOME_LABEL[r.outcome]}</td>
                    <td className="py-2 pr-3 text-right font-mono">{r.daysToFirstAnswer === null ? "—" : r.daysToFirstAnswer}</td>
                    <td className="py-2 pr-3">
                      <a href={r.issueUrl} className={linkCls} rel="noopener">
                        #{r.issue}
                      </a>
                    </td>
                    <td className="py-2 align-top">
                      <details data-access-report-share={r.issue}>
                        <summary className={`cursor-pointer ${linkCls}`}>Share</summary>
                        <ShareRow
                          place={`access-report-${vendor}`}
                          label={`Share report #${r.issue}`}
                          text={shareText(r)}
                          url={shareUrl(r, site.url)}
                        />
                      </details>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <div className="mt-4 flex flex-wrap items-center gap-x-4 gap-y-2">
            {button}
            <span className="text-xs text-[var(--muted)]">
              {`Imported ${ACCESS_REPORTS_IMPORTED_ON}. Program, requests and notes are in each issue.`}{" "}
              <a href={`${REPO_URL}/issues?q=${encodeURIComponent(`is:issue label:${ACCEPT_LABEL}`)}`} className={linkCls} rel="noopener">
                All accepted reports
              </a>
            </span>
          </div>
        </div>
      )}

      <div data-access-badge={badgePath} data-badge-alt={badgeAlt(badge)} className="mt-6 border-t border-[var(--border)] pt-4">
        <p className="text-xs font-semibold uppercase tracking-wider text-[var(--muted)]">Badge for a README</p>
        <p className="mt-2">
          <img src={badgePath} alt={badgeAlt(badge)} height={20} loading="lazy" />
        </p>
        <pre
          aria-label={`Markdown for the ${v.name} access-report badge`}
          className="mt-2 overflow-x-auto rounded-xl border border-[var(--border)] bg-[var(--bg)] p-3 text-xs leading-relaxed text-[var(--fg)]"
        >
          <code>{badgeMarkdown(accessBadgeAlt(v.name), badgePath, `${v.pages[0]}#access-reports`)}</code>
        </pre>
        <p className="mt-2 text-xs text-[var(--muted)]">
          {"The image is redrawn from these reports each time they are imported: the count, and the median once it is shown here."}
        </p>
      </div>
    </section>
  );
}
