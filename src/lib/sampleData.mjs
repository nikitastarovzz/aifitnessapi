const HC_CLASS = {
  steps: { className: "StepsRecord", value: "count" },
  restingHeartRate: { className: "RestingHeartRateRecord", value: "beatsPerMinute" },
  hrv: { className: "HeartRateVariabilityRmssdRecord", value: "heartRateVariabilityMillis" },
  activeEnergy: { className: "ActiveCaloriesBurnedRecord", value: "energy" },
  distance: { className: "DistanceRecord", value: "distance" },
  weight: { className: "WeightRecord", value: "weight" },
  spo2: { className: "OxygenSaturationRecord", value: "percentage" },
  sleep: { className: "SleepSessionRecord", value: null },
  workout: { className: "ExerciseSessionRecord", value: "exerciseType" },
};

/** Kotlin unit classes this tool encodes as {value, unit}; the unit word comes from Google's range sentence. */
const HC_UNIT_CLASSES = { Energy: /\bkcal\b/, Length: /\bmeters\b/, Mass: /\bkilograms\b/ };

function healthConnectSpecs({ HC_RECORDS, HC_FETCHED_ON, workouts }) {
  const specs = [];
  for (const { metric, label } of METRICS) {
    const c = HC_CLASS[metric];
    if (!c) continue;
    const r = HC_RECORDS.find((x) => x.className === c.className);
    if (!r) fail(`${c.className} not in the Health Connect dataset`);
    const prop = (name) => {
      const p = r.properties.find((x) => x.name === name);
      if (!p) fail(`${r.className}.${name} not in the dataset`);
      return p;
    };
    const instant = r.recordShape === "Instantaneous";
    const timeFields = instant ? ["time", "zoneOffset"] : ["startTime", "startZoneOffset", "endTime", "endZoneOffset"];
    for (const t of timeFields) prop(t);
    const fields = timeFields.map((t) => {
      const p = prop(t);
      return t.endsWith("ffset")
        ? { name: t, type: p.type, note: "written as \"+HH:MM\"; null when you untick offsets (the type is nullable)" }
        : { name: t, type: p.type, note: "ISO 8601 instant, UTC" };
    });
    const spec = {
      platform: "health-connect",
      metric,
      label,
      typeName: r.className,
      typeLabel: r.qualifiedName,
      shape: instant ? "sample" : metric === "sleep" || metric === "workout" ? "session" : "interval",
      tabular: true,
      docUrl: r.sourceUrl,
      valueField: c.value,
      fields,
      omitted: [],
    };
    if (c.value && metric !== "workout") {
      const p = prop(c.value);
      const range = parseRange(p.rangeStatement) ?? (p.range ? { min: Number(p.range.from), max: Number(p.range.to) } : null);
      spec.valueType = p.type;
      spec.range = range;
      const unitRe = HC_UNIT_CLASSES[p.type];
      if (unitRe) {
        const m = unitRe.exec(p.rangeStatement ?? "");
        if (!m) fail(`${r.className}.${c.value}: Google's range sentence no longer names the unit`);
        spec.valueUnit = m[0];
        fields.push({ name: c.value, type: p.type, note: `{ value, unit: "${m[0]}" } — unit from Google's sentence "${p.rangeStatement}"` });
      } else {
        fields.push({ name: c.value, type: p.type, note: p.rangeStatement ?? "no range stated" });
      }
    }
    if (metric === "sleep") {
      const p = prop("stages");
      if (p.constructorDefault !== "emptyList()") fail("SleepSessionRecord.stages no longer defaults to emptyList()");
      fields.push({ name: "stages", type: p.type, note: "always [] — the constructor's default" });
      spec.omitted.push({ name: "stages[] contents", reason: "SleepSessionRecord.Stage's fields are not in this site's dataset; the STAGE_TYPE_* constants are, but not the class that carries them" });
    }
    if (metric === "workout") {
      const p = prop("exerciseType");
      spec.workouts = workouts.map((w) => {
        const k = r.constants.find((x) => x.name === w.healthConnect);
        if (!k || k.value === null) fail(`${w.healthConnect} not among ExerciseSessionRecord's constants`);
        return { key: w.key, name: k.name, value: Number(k.value) };
      });
      fields.push({ name: "exerciseType", type: p.type, note: `the constant's value: ${spec.workouts.map((w) => `${w.name} = ${w.value}`).join(", ")}` });
      fields.push({ name: "exerciseTypeName", type: "string", note: "not a record field — the constant's name, for your reading" });
      for (const name of ["segments", "laps"]) {
        const q = prop(name);
        if (q.constructorDefault !== "emptyList()") fail(`ExerciseSessionRecord.${name} no longer defaults to emptyList()`);
      }
      spec.omitted.push({ name: "segments, laps, route", reason: "left at the constructor's defaults; their element classes are not in this site's dataset" });
    }
    spec.omitted.push({ name: "metadata", reason: "every constructor requires a Metadata, but Metadata's fields are not in this site's dataset" });
    if (r.className === "OxygenSaturationRecord") {
      spec.omitted.push({ name: "Percentage encoding", reason: "written as a bare number in Google's stated 0–100 range" });
    }

    const params = ctorParams(r.constructors[0] ?? fail(`${r.className} has no constructor`));
    const generated = new Set([...timeFields, ...(c.value ? [c.value] : []), ...(metric === "sleep" ? ["stages"] : [])]);
    const pad = Math.max(...params.map((p) => p.name.length)) + 2;
    spec.snippet = [
      `// ${r.className} constructor as Google's Jetpack reference prints it (read ${HC_FETCHED_ON}):`,
      ...r.constructors[0].split("\n").map((l) => `// ${l}`),
      "//",
      "// constructor parameter <- fixture field",
      ...params.map((p) =>
        generated.has(p.name)
          ? `//   ${p.name.padEnd(pad)}<- ${p.name}`
          : `//   ${p.name.padEnd(pad)}<- not generated${p.type.includes("=") ? " (has a default)" : ""}`,
      ),
    ].join("\n");
    specs.push(spec);
  }
  return specs;
}

