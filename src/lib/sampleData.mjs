const GH_SUMMARY_FIELDS = ["caloriesKcal", "distanceMillimeters", "steps", "averageHeartRateBeatsPerMinute"];
const GH_STAGE_TYPES = ["LIGHT", "DEEP", "REM", "AWAKE"];

function ghField(S, schemaId, name) {
  const s = S[schemaId] ?? fail(`schema ${schemaId} not in the discovery data`);
  return s.fields.find((f) => f.name === name) ?? fail(`${schemaId}.${name} not in the discovery data`);
}

/** The required, writable fields of a time schema, with the discovery types. */
function ghTimeFields(S, schemaId) {
  const s = S[schemaId] ?? fail(`schema ${schemaId} missing`);
  const order = ["physicalTime", "utcOffset", "startTime", "startUtcOffset", "endTime", "endUtcOffset"];
  const rank = (n) => (order.indexOf(n) === -1 ? order.length : order.indexOf(n));
  return s.fields
    .filter((f) => f.required && !f.readOnly)
    .map((f) => ({ name: f.name, type: f.type }))
    .sort((a, b) => rank(a.name) - rank(b.name));
}

function googleSpecs({ GHAPI_DATA_TYPES, GHAPI_SCHEMAS: S, GHAPI_DISCOVERY, workouts }) {
  const specs = [];
  for (const { metric, label } of METRICS) {
    const prop = GH_PROPERTY[metric];
    if (!prop) continue;
    const d = GHAPI_DATA_TYPES.find((x) => x.dataPointProperty === prop);
    if (!d || !d.schema) fail(`Google Health API data type for ${prop} not found`);
    if (d.channel !== "v4") fail(`${d.dataType} is no longer on the v4 channel`);
    const schemaId = d.schema.id;
    const cfg = GH_FIELDS[prop];
    const timeField = ghField(S, schemaId, cfg.time);
    const timeSchema = timeField.ref ?? fail(`${schemaId}.${cfg.time} has no schema ref`);
    // A Daily type is keyed by a civil Date, whose fields carry no "Required." label.
    const timeFields =
      timeSchema === "Date"
        ? ["year", "month", "day"].map((n) => ({ name: n, type: ghField(S, "Date", n).type }))
        : ghTimeFields(S, timeSchema);
    const readOnly = S[timeSchema].fields.filter((f) => f.readOnly).map((f) => f.name);
    const list = d.operations.find((o) => o.op === "list");
    const spec = {
      platform: "google-health-api",
      metric,
      label,
      typeName: d.dataType,
      typeLabel: `${d.name} (${d.dataType})`,
      dataPointProperty: prop,
      schemaId,
      shape: d.recordType === "Sample" ? "sample" : d.recordType === "Session" ? "session" : d.recordType === "Daily" ? "daily" : "interval",
      tabular: metric !== "sleep",
      docUrl: d.referenceUrl,
      timeField: cfg.time,
      timeSchema,
      timeFields,
      listPath: list?.path ?? null,
      fields: [
        { name: `${prop}.${cfg.time}`, type: timeSchema, note: timeFields.map((f) => `${f.name}: ${f.type}`).join("; ") },
      ],
      omitted: [
        ...(readOnly.length ? [{ name: readOnly.join(", "), reason: "Output only in the discovery document — the server computes them" }] : []),
        { name: "name, dataSource", reason: "DataPoint's wrapper fields are not in this site's schema extract; only the data-type union member is generated" },
      ],
    };
    if (cfg.value) {
      const f = ghField(S, schemaId, cfg.value);
      spec.valueField = cfg.value;
      spec.valueType = f.type;
      spec.range = parseRange(f.description);
      spec.fields.push({ name: `${prop}.${cfg.value}`, type: f.type, note: f.description });
    }
    if (prop === "sleep") {
      const typeF = ghField(S, schemaId, "type");
      if (!typeF.enum?.some((e) => e.value === "STAGES")) fail("Sleep.type no longer has STAGES");
      const stages = ghField(S, schemaId, "stages");
      const stageType = ghField(S, stages.itemsRef ?? "SleepStage", "type");
      for (const t of GH_STAGE_TYPES) if (!stageType.enum?.some((e) => e.value === t)) fail(`SleepStage.type lacks ${t}`);
      spec.stageFields = ghTimeFields(S, stages.itemsRef ?? "SleepStage").filter((f) => f.name !== "type");
      spec.fields.push({ name: "sleep.type", type: typeF.type, note: "always STAGES" });
      spec.fields.push({ name: "sleep.stages[]", type: stages.type, note: `${stages.description} type ∈ ${GH_STAGE_TYPES.join(", ")}` });
      spec.omitted.push({ name: "outOfBedSegments, metadata", reason: "optional; not generated" });
    }
    if (prop === "exercise") {
      const et = ghField(S, schemaId, "exerciseType");
      spec.workouts = workouts.map((w) => {
        if (!et.enum?.some((e) => e.value === w.google)) fail(`Exercise.exerciseType lacks ${w.google}`);
        return { key: w.key, name: w.google };
      });
      const dn = ghField(S, schemaId, "displayName");
      const ms = ghField(S, schemaId, "metricsSummary");
      spec.summaryFields = GH_SUMMARY_FIELDS.map((n) => {
        const f = ghField(S, ms.ref ?? "MetricsSummary", n);
        return { name: n, type: f.type };
      });
      spec.fields.push({ name: "exercise.exerciseType", type: et.type, note: spec.workouts.map((w) => w.name).join(", ") });
      spec.fields.push({ name: "exercise.displayName", type: dn.type, note: dn.description });
      spec.fields.push({ name: "exercise.metricsSummary", type: ms.ref ?? "MetricsSummary", note: spec.summaryFields.map((f) => `${f.name}: ${f.type}`).join("; ") });
      spec.omitted.push({ name: "exerciseEvents, splits, splitSummaries, exerciseMetadata", reason: "optional; not generated" });
    }
    spec.snippet = [
      `// ${d.name}: a DataPoint carries it under "${prop}" (discovery ${GHAPI_DISCOVERY.revision ? `v4 revision ${GHAPI_DISCOVERY.revision}` : "v4"}).`,
      list?.path ? `// Returned by: ${list.httpMethod} ${list.path}` : "// (no list method in Google's table for this type)",
      `// Schema ${schemaId}:`,
      ...spec.fields.map((f) => `//   ${f.name}: ${f.type}`),
      "// int64 fields are JSON strings and offsets are durations in seconds (\"0s\"), as Google's own list example prints them.",
    ].join("\n");
    specs.push(spec);
  }
  return specs;
}

/**
 * Everything the client needs, from the generated modules. Pass the modules'
 * exports in; nothing here imports them, so the node test can call it too.
 */
export function buildSampleSpecs(data) {
  const { WT_CROSSWALK } = data;
  const workouts = WORKOUT_KEYS.map((key) => {
    const row = WT_CROSSWALK.find((r) => r.key === key) ?? fail(`workout crosswalk row ${key} missing`);
    const cell = (p) => row.cells.find((c) => c.platform === p)?.name ?? fail(`${key} has no ${p} constant`);
    return { key, healthkit: cell("healthkit"), healthConnect: cell("health-connect"), google: cell("google-health-api") };
  });
  const specs = [
    ...healthkitSpecs({ ...data, workouts }),
    ...healthConnectSpecs({ ...data, workouts }),
    ...googleSpecs({ ...data, workouts }),
  ];
  return {
    specs,
    sources: {
      healthkit: { fetchedOn: data.HK_FETCHED_ON, metadataKeysFetchedOn: data.HK_METADATA_KEYS_FETCHED_ON },
      "health-connect": { fetchedOn: data.HC_FETCHED_ON },
      "google-health-api": { fetchedOn: data.GHAPI_FETCHED_ON, revision: data.GHAPI_DISCOVERY?.revision ?? null },
      workouts: { fetchedOn: data.WT_FETCHED_ON },
    },
  };
}

// ─── Runtime: deterministic generation ───────────────────────────────────

function fnv1a(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

function mulberry32(a) {
  return function () {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** A seeded stream: rand() in [0,1), int(lo,hi) inclusive, range(lo,hi). */
export function rng(seed, stream) {
  const r = mulberry32(fnv1a(`${seed}|${stream}`));
  return {
    rand: r,
    int: (lo, hi) => lo + Math.floor(r() * (hi - lo + 1)),
    range: (lo, hi) => lo + r() * (hi - lo),
  };
}

const dtfCache = new Map();
/** Minutes east of UTC in force at `ms` in `timeZone`, from the platform tz database. */
export function offsetMinutes(ms, timeZone) {
  let dtf = dtfCache.get(timeZone);
  if (!dtf) {
    dtf = new Intl.DateTimeFormat("en-US", {
      timeZone,
      hour12: false,
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
    });
    dtfCache.set(timeZone, dtf);
  }
  const p = Object.fromEntries(dtf.formatToParts(new Date(ms)).map((x) => [x.type, x.value]));
  const asUTC = Date.UTC(+p.year, +p.month - 1, +p.day, p.hour === "24" ? 0 : +p.hour, +p.minute, +p.second);
  return Math.round((asUTC - Math.floor(ms / 1000) * 1000) / 60000);
}

/** The instant a local civil time names in `timeZone`. In a spring-forward gap it lands after the gap. */
export function zonedToUtc(y, mo, d, h, mi, timeZone) {
  const t = Date.UTC(y, mo, d, h, mi);
  const off = offsetMinutes(t, timeZone);
  let u = t - off * 60000;
  const off2 = offsetMinutes(u, timeZone);
  if (off2 !== off) u = t - off2 * 60000;
  return u;
}

/** "+05:30" / "-04:00" / "+00:00". */
export function isoOffset(min) {
  const s = min < 0 ? "-" : "+";
  const a = Math.abs(min);
  return `${s}${String(Math.floor(a / 60)).padStart(2, "0")}:${String(a % 60).padStart(2, "0")}`;
}

/** google-duration in seconds, as Google's example prints it ("0s"). */
export function durationOffset(min) {
  return `${min * 60}s`;
}

const iso = (ms) => new Date(ms).toISOString().replace(".000Z", "Z");

/** Civil dates from start to end inclusive ("YYYY-MM-DD"). */
export function civilDays(start, end) {
  const [y1, m1, d1] = start.split("-").map(Number);
  const [y2, m2, d2] = end.split("-").map(Number);
  const out = [];
  for (let t = Date.UTC(y1, m1 - 1, d1); t <= Date.UTC(y2, m2 - 1, d2); t += 86400000) {
    const dt = new Date(t);
    out.push({ y: dt.getUTCFullYear(), mo: dt.getUTCMonth(), d: dt.getUTCDate(), date: dt.toISOString().slice(0, 10) });
  }
  return out;
}

/** Every change of UTC offset in the generated span, in the zone. */
export function offsetTransitions(start, end, timeZone) {
  const days = civilDays(start, end);
  if (!days.length) return [];
  const a = zonedToUtc(days[0].y, days[0].mo, days[0].d, 0, 0, timeZone);
  const last = days[days.length - 1];
  // Through noon after the last day: the last night's sleep ends the next morning.
  const b = zonedToUtc(last.y, last.mo, last.d + 1, 12, 0, timeZone);
  const out = [];
  let prev = offsetMinutes(a, timeZone);
  for (let t = a + 900000; t <= b; t += 900000) {
    const o = offsetMinutes(t, timeZone);
    if (o !== prev) {
      out.push({ at: iso(t), from: isoOffset(prev), to: isoOffset(o) });
      prev = o;
    }
  }
  return out;
}

/* ── Platform-neutral events: one stream per metric, shared by every platform ── */

const FOOT = new Set(["running", "walking", "hiking"]);

function events(metric, days, tz, seed) {
  const r = rng(seed, metric);
  const out = [];
  const at = (day, h, mi) => zonedToUtc(day.y, day.mo, day.d, h, mi, tz);
  if (metric === "steps" || metric === "activeEnergy" || metric === "distance") {
    // Hourly buckets over waking hours, 07:00–22:00 local. Distance reuses the steps stream.
    const s = rng(seed, metric === "activeEnergy" ? "activeEnergy" : "steps");
    for (const day of days) {
      for (let h = 7; h < 22; h++) {
        const start = at(day, h, 0);
        const end = at(day, h + 1, 0);
        const idle = s.rand() < 0.15;
        const steps = idle ? 0 : s.int(40, 900);
        if (metric === "activeEnergy") out.push({ start, end, value: idle ? 0 : Math.round(s.range(4, 60) * 10) / 10 });
        else if (metric === "steps") out.push({ start, end, value: steps });
        else out.push({ start, end, value: Math.round(steps * 0.72 * 10) / 10 }); // metres; illustrative stride
      }
    }
  } else if (metric === "heartRate") {
    for (const day of days) {
      const a = at(day, 0, 0);
      const b = zonedToUtc(day.y, day.mo, day.d + 1, 0, 0, tz);
      for (let t = a; t < b; t += 600000) {
        const hourLocal = (new Date(t + offsetMinutes(t, tz) * 60000).getUTCHours());
        const base = hourLocal < 7 ? 58 : 74;
        out.push({ start: t, end: t, value: Math.round(base + r.range(-6, 14)) });
      }
    }
  } else if (metric === "restingHeartRate") {
    for (const day of days) {
      const t = at(day, 7, r.int(0, 40));
      out.push({ start: t, end: t, value: r.int(52, 68) });
    }
  } else if (metric === "hrv") {
    for (const day of days) {
      const t = at(day, 6, r.int(0, 50));
      out.push({ start: t, end: t, value: Math.round(r.range(25, 70) * 10) / 10 });
    }
  } else if (metric === "weight") {
    let kg = r.range(62, 84);
    for (const day of days) {
      kg += r.range(-0.3, 0.3);
      const t = at(day, 7, r.int(5, 30));
      out.push({ start: t, end: t, value: Math.round(kg * 10) / 10 });
    }
  } else if (metric === "spo2") {
    for (const day of days) {
      const t = at(day, 4, r.int(0, 59));
      out.push({ start: t, end: t, value: r.int(95, 99) });
    }
  } else if (metric === "sleep") {
    // Bedtime is a local civil time; the length is absolute — so a night across a DST change
    // starts and ends on different offsets.
    for (const day of days) {
      const start = at(day, 22, r.int(30, 105));
      const minutes = r.int(390, 510);
      const end = start + minutes * 60000;
      const stages = [];
      let t = start;
      const pattern = ["LIGHT", "DEEP", "LIGHT", "REM"];
      let i = 0;
      while (t < end) {
        const type = r.rand() < 0.06 ? "AWAKE" : pattern[i++ % pattern.length];
        const len = type === "AWAKE" ? r.int(2, 8) : type === "DEEP" ? r.int(15, 40) : r.int(10, 30);
        const next = Math.min(end, t + len * 60000);
        stages.push({ start: t, end: next, type });
        t = next;
      }
      out.push({ start, end, stages });
    }
  } else if (metric === "workout") {
    days.forEach((day, i) => {
      if (i % 2 === 1) return;
      const start = at(day, 18, r.int(0, 45));
      const minutes = r.int(25, 60);
      const activity = WORKOUT_KEYS[r.int(0, WORKOUT_KEYS.length - 1)];
      const foot = FOOT.has(activity);
      out.push({
        start,
        end: start + minutes * 60000,
        activity,
        kcal: Math.round(minutes * r.range(5, 9)),
        meters: foot ? Math.round(minutes * (activity === "running" ? r.range(150, 190) : r.range(70, 95))) : null,
        steps: foot ? Math.round(minutes * (activity === "running" ? r.range(150, 170) : r.range(95, 115))) : null,
        avgBpm: r.int(activity === "yoga" ? 85 : 105, activity === "yoga" ? 110 : 150),
      });
    });
  }
  return out;
}

/* ── Platform encoders ── */

function inRange(spec, v) {
  return !spec.range || (v >= spec.range.min && v <= spec.range.max);
}

function encodeHealthKit(spec, evs, tz, attachZone) {
  const meta = attachZone ? { metadata: { HKMetadataKeyTimeZone: tz } } : {};
  if (spec.metric === "workout") {
    return evs.map((e) => {
      const w = spec.workouts.find((x) => x.key === e.activity);
      return { workoutActivityType: w.objc, startDate: iso(e.start), endDate: iso(e.end), ...meta };
    });
  }
  // An idle hour writes no cumulative sample rather than a zero one.
  return evs
    .filter((e) => !(spec.aggregation === "cumulative" && e.value === 0))
    .map((e) => ({
      type: spec.typeName,
      startDate: iso(e.start),
      endDate: iso(e.end),
      value: e.value,
      unitFamily: spec.unitFamily,
      valueUnit: spec.valueUnit,
      ...meta,
    }));
}

function encodeHealthConnect(spec, evs, tz, withOffsets) {
  const off = (ms) => (withOffsets ? isoOffset(offsetMinutes(ms, tz)) : null);
  const time = (e) =>
    spec.shape === "sample"
      ? { time: iso(e.start), zoneOffset: off(e.start) }
      : { startTime: iso(e.start), startZoneOffset: off(e.start), endTime: iso(e.end), endZoneOffset: off(e.end) };
  if (spec.metric === "sleep") return evs.map((e) => ({ ...time(e), stages: [] }));
  if (spec.metric === "workout") {
    return evs.map((e) => {
      const w = spec.workouts.find((x) => x.key === e.activity);
      return { ...time(e), exerciseType: w.value, exerciseTypeName: w.name };
    });
  }
  const v = (e) => e.value;
  const out = [];
  for (const e of evs) {
    if (!inRange(spec, e.value)) continue; // e.g. StepsRecord's count starts at 1, so idle hours are not written
    out.push({ ...time(e), [spec.valueField]: spec.valueUnit ? { value: v(e), unit: spec.valueUnit } : v(e) });
  }
  return out;
}

function ghScalar(type, v) {
  if (type === "string/int64") return String(Math.round(v));
  return v;
}

function encodeGoogle(spec, evs, tz) {
  const timeObj = (e, fields) => {
    const o = {};
    for (const f of fields) {
      if (f.name === "physicalTime") o.physicalTime = iso(e.start);
      else if (f.name === "year" || f.name === "month" || f.name === "day") {
        // The civil date in the user's zone at the reading's instant.
        const local = new Date(e.start + offsetMinutes(e.start, tz) * 60000);
        o[f.name] = f.name === "year" ? local.getUTCFullYear() : f.name === "month" ? local.getUTCMonth() + 1 : local.getUTCDate();
      }
      else if (f.name === "utcOffset") o.utcOffset = durationOffset(offsetMinutes(e.start, tz));
      else if (f.name === "startTime") o.startTime = iso(e.start);
      else if (f.name === "endTime") o.endTime = iso(e.end);
      else if (f.name === "startUtcOffset") o.startUtcOffset = durationOffset(offsetMinutes(e.start, tz));
      else if (f.name === "endUtcOffset") o.endUtcOffset = durationOffset(offsetMinutes(e.end, tz));
      else throw new Error(`sample-data: unhandled time field ${f.name}`);
    }
    return o;
  };
  const p = spec.dataPointProperty;
  const pts = [];
  for (const e of evs) {
    let body;
    if (p === "sleep") {
      body = {
        [spec.timeField]: timeObj(e, spec.timeFields),
        type: "STAGES",
        stages: e.stages.map((s) => ({ ...timeObj(s, spec.stageFields), type: s.type })),
      };
    } else if (p === "exercise") {
      const w = spec.workouts.find((x) => x.key === e.activity);
      const sum = {};
      const vals = { caloriesKcal: e.kcal, distanceMillimeters: e.meters === null ? null : e.meters * 1000, steps: e.steps, averageHeartRateBeatsPerMinute: e.avgBpm };
      for (const f of spec.summaryFields) if (vals[f.name] !== null) sum[f.name] = ghScalar(f.type, vals[f.name]);
      body = { [spec.timeField]: timeObj(e, spec.timeFields), exerciseType: w.name, displayName: w.name.charAt(0) + w.name.slice(1).toLowerCase(), metricsSummary: sum };
    } else {
      let v = e.value;
      if (p === "distance") v = e.value * 1000; // metres → millimeters, the field's unit
      if (p === "weight") v = Math.round(e.value * 1000); // kg → grams
      if (!inRange(spec, v)) continue;
      body = { [spec.timeField]: timeObj(e, spec.timeFields), [spec.valueField]: ghScalar(spec.valueType, v) };
    }
    pts.push({ [p]: body });
  }
  return { dataPoints: pts };
}

/**
 * Generate one platform's fixtures.
 * opts: { specs, platform, metrics: string[], start: "YYYY-MM-DD", end, timeZone, seed, offsets: boolean }
 */
export function generateSampleData(opts) {
  const { specs, platform, metrics, start, end, timeZone, seed } = opts;
  const offsets = opts.offsets !== false;
  const days = civilDays(start, end);
  if (days.length === 0) throw new Error("end date is before start date");
  if (days.length > MAX_DAYS) throw new Error(`at most ${MAX_DAYS} days`);
  const records = {};
  const counts = {};
  for (const spec of specs) {
    if (spec.platform !== platform || !metrics.includes(spec.metric)) continue;
    const evs = events(spec.metric, days, timeZone, String(seed));
    let rec;
    if (platform === "healthkit") rec = encodeHealthKit(spec, evs, timeZone, offsets);
    else if (platform === "health-connect") rec = encodeHealthConnect(spec, evs, timeZone, offsets);
    else rec = encodeGoogle(spec, evs, timeZone);
    records[spec.typeName] = rec;
    counts[spec.typeName] = Array.isArray(rec) ? rec.length : rec.dataPoints.length;
  }
  return {
    _synthetic: {
      notice: SAMPLE_DATA_NOTICE,
      generator: "https://aifitnessapi.com/tools/sample-data",
      platform,
      seed: String(seed),
      timeZone,
      range: { start, end },
      offsets: platform === "google-health-api" ? true : offsets,
      offsetTransitions: offsetTransitions(start, end, timeZone),
      counts,
      encoding:
        platform === "google-health-api"
          ? "Each type is shaped like the list method's response: { dataPoints: [ { <dataType property>: {...} } ] }. Output-only and DataPoint wrapper fields are omitted."
          : platform === "health-connect"
            ? "Health Connect is a Kotlin API with no JSON format. Each record is this tool's JSON encoding of the record class: field names are the class's properties; Instants are ISO 8601 UTC; ZoneOffsets are \"+HH:MM\" or null; Energy/Length/Mass are { value, unit }."
            : "HealthKit has no JSON wire format. Each sample is this tool's encoding: the type identifier, start and end as ISO 8601 UTC instants, a value in the stated unit family, and the zone as HKMetadataKeyTimeZone when attached.",
    },
    records,
  };
}

/* ── CSV ── */

function flatten(obj, prefix, out) {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v !== null && typeof v === "object" && !Array.isArray(v)) flatten(v, key, out);
    else if (Array.isArray(v)) out[key] = v.length === 0 ? "" : JSON.stringify(v);
    else out[key] = v;
  }
  return out;
}

function cell(v) {
  if (v === null || v === undefined) return "";
  const s = String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/** One type's records as CSV, with a leading `_synthetic` column on every row. */
export function toCsv(records) {
  const list = Array.isArray(records) ? records : records.dataPoints;
  const rows = list.map((r) => flatten(r, "", {}));
  const cols = [];
  for (const r of rows) for (const k of Object.keys(r)) if (!cols.includes(k)) cols.push(k);
  const head = ["_synthetic", ...cols].join(",");
  return [head, ...rows.map((r) => ["SYNTHETIC TEST DATA", ...cols.map((c) => cell(r[c]))].join(","))].join("\n") + "\n";
}
