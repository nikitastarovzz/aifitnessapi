/**
 * Synthetic test-data generator behind /tools/sample-data.
 *
 * Two halves, both pure and dependency-free so the page, the browser and the
 * node test run the same code:
 *
 *   buildSampleSpecs(data)  — runs at build time on the server. It reads the
 *     generated datasets (HealthKit identifiers + metadata keys, Health
 *     Connect records, the Google Health API discovery schemas, the workout
 *     crosswalk) and returns a small, JSON-serialisable spec per offered
 *     type. Every field name a fixture will carry is looked up in those
 *     modules here, and a missing one throws: a regeneration that renames a
 *     field fails the build instead of shipping a fixture with a stale name.
 *     Nothing from the full datasets reaches the browser beyond these specs.
 *
 *   generateSampleData(opts) — runs in the browser. A seeded PRNG (FNV-1a →
 *     mulberry32), one stream per metric so adding a type never changes
 *     another type's values, and civil-time → instant conversion through the
 *     platform's own tz database (Intl), so every record's offset is the one
 *     in force at that record's instant — a night that spans a DST change
 *     gets two different offsets, as it would on a device.
 *
 * The values are SYNTHETIC. The ranges below are illustrative and
 * conservative, chosen to look plausible in a UI, not physiologically
 * validated, and they are clamped to the validation range each platform's
 * own reference states wherever the dataset carries one.
 */

