function fail(msg) {
  throw new Error(`sample-data spec: ${msg}`);
}

/** "Valid range: 1-1000000." / "Must be in the range `[0, 100]`." → {min,max}; null when absent. */
export function parseRange(text) {
  if (!text) return null;
  const m = /(-?\d+(?:\.\d+)?)\s*(?:-|,)\s*(-?\d+(?:\.\d+)?)/.exec(text);
  return m ? { min: Number(m[1]), max: Number(m[2]) } : null;
}

/** Constructor parameters as Google prints them: [{name, type}]. */
function ctorParams(ctor) {
  const inner = ctor.slice(ctor.indexOf("(") + 1, ctor.lastIndexOf(")"));
  return inner
    .split("\n")
    .map((l) => l.trim().replace(/,$/, ""))
    .filter(Boolean)
    .map((l) => {
      const i = l.indexOf(":");
      return { name: l.slice(0, i).trim(), type: l.slice(i + 1).trim() };
    });
}

