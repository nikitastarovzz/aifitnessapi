/**
 * Shared JSON-LD builders. One stable Organization @id is referenced from the
 * WebSite node and from every page's author/publisher, so search engines treat
 * the whole site as one entity (E-E-A-T / knowledge-graph signal).
 *
 * Vocabulary discipline: every type and property emitted from this file was
 * checked against the published schema.org vocabulary (schemaorg release
 * 29.1) — including its declared domain, which is why `lastReviewed` and
 * `reviewedBy` are attached to a WebPage node and never to the Article.
 */
import { site, absoluteUrl } from "@/lib/site";
import { termsDefining, termId } from "@/data/glossary";
import { PUBLISHED } from "@/data/published";
import type { ClusterEntry } from "@/lib/cluster";

export const ORG_ID = `${site.url}/#organization`;
export const WEBSITE_ID = `${site.url}/#website`;

/**
 * datePublished for a page, from the git-derived first-published map
 * (src/data/published.ts, generated by scripts/backfill-published.mjs).
 *
 * `key` is the URL path without its leading slash. A page newer than the last
 * regeneration has no row and falls back to `modified` — the same date every
 * page carried before the map existed, so a stale map degrades to the old
 * behaviour rather than to a guess.
 *
 * Clamped to never exceed `modified`. That is not hypothetical: an `updated`
 * stamp records when the facts were checked, and research can predate the
 * commit that ships it — 66 spokes were verified one to four days before
 * they were committed when the map was first generated. A datePublished after
 * dateModified is an inconsistency validators flag, and the two ways out are
 * not equal: moving dateModified forward would claim a re-verification that
 * never happened (the one number CLAUDE.md says must not be falsified), while
 * pulling datePublished back to the verification date only says the page's
 * content is as of the day it was checked — which is true.
 */
export function publishedDate(key: string, modified: string): string {
  const first = PUBLISHED[key] ?? modified;
  return first > modified ? modified : first;
}

/** Markdown mirror URL for a page path, per the llms.txt convention of
 *  serving the same URL with `.md` appended. */
export function markdownUrl(path: string): string {
  const clean = path.startsWith("/") ? path : `/${path}`;
  return absoluteUrl(clean === "/" ? "/index.md" : `${clean}.md`);
}

