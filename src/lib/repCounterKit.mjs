/**
 * public/kit/rep-counter.html: a squat rep counter in one HTML file, rendered
 * from scripts/templates/rep-counter.template.html by scripts/build-kit.mjs.
 *
 * Nothing in the file is typed by hand. Every value is read here from a
 * module or evidence file the site already publishes, and the render refuses
 * to run if one is missing:
 *
 *  - runtime version and URLs: src/lib/poseBenchmark.ts (checked on its
 *    VERIFIED_ON), the same pinned files /tools/pose-benchmark loads;
 *  - the count thresholds: the knee_angle lines Sousa and colleagues mark
 *    "default, adjustable", as quoted in
 *    ops/sources/evidence/motion-squat-detection-pose-estimation.json, and
 *    required to equal the /challenge squat rule in src/lib/repCounter.mjs;
 *  - the stance cue: the squat-stance-ratio-exercise-correction row of
 *    src/data/formRules.ts (generated by scripts/fetch-form-rules.mjs).
 *
 * Pure: the caller passes the modules in, so scripts/rep-counter-kit.test.mjs
 * renders exactly what the build writes.
 */

export const KIT_FILE = "public/kit/rep-counter.html";
export const TEMPLATE_FILE = "scripts/templates/rep-counter.template.html";
export const STANCE_ROW_ID = "squat-stance-ratio-exercise-correction";
export const SQUAT_PAGE_SLUG = "squat-detection-pose-estimation";
const SITE = "https://aifitnessapi.com";

const decode = (s) => s.replace(/&gt;/g, ">").replace(/&lt;/g, "<").replace(/&quot;/g, '"').replace(/&amp;/g, "&");
const escapeHtml = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/**
 * Every value the template needs, from the site's own modules.
 * @param {{
 *   poseBenchmark: { TASKS_VISION_VERSION: string, TASKS_VISION_BUNDLE: string, TASKS_VISION_WASM: string, TASKS_VISION_USAGE_LOG_URL: string, BENCH_MODELS: { id: string, name: string, url: string }[] },
 *   formRules: { FORM_RULES: any[], FORM_RULE_SOURCES: any[], FORM_RULES_FETCHED_ON: string },
 *   squatEvidence: { claim: string, url: string, quote: string }[],
 *   squatEntry: { slug: string, sources?: { url: string, note?: string }[] },
 *   counter: { rest: { above?: number }, active: { below?: number } },
 * }} input
 */
export function kitValues({ poseBenchmark, formRules, squatEvidence, squatEntry, counter }) {
  const fail = (m) => {
    throw new Error(`rep-counter kit: ${m}`);
  };
  const lite = poseBenchmark.BENCH_MODELS.find((m) => m.id === "lite") ?? fail("no lite model in src/lib/poseBenchmark.ts");

  const knee = (op) => {
    for (const row of squatEvidence) {
      const q = decode(row.quote ?? "");
      const m = new RegExp(`^knee_angle ${op} (\\d+) # default, adjustable$`).exec(q.trim());
      if (m) return { value: Number(m[1]), quote: q.trim(), url: row.url };
    }
    return fail(`no "knee_angle ${op} N # default, adjustable" quote in the squat evidence file`);
  };
  const top = knee(">");
  const bottom = knee("<");
  if (top.value !== counter.rest.above || bottom.value !== counter.active.below) {
    fail(`evidence says ${top.value}/${bottom.value} but the /challenge squat rule is ${counter.rest.above}/${counter.active.below}`);
  }
  const pmc = /PMC\d+/.exec(top.url)?.[0] ?? fail(`no PMC id in ${top.url}`);
  if (squatEntry.slug !== SQUAT_PAGE_SLUG) fail(`expected the ${SQUAT_PAGE_SLUG} entry, got ${squatEntry.slug}`);
  const study = (squatEntry.sources ?? []).find((s) => s.url.includes(pmc)) ?? fail(`${SQUAT_PAGE_SLUG} lists no source for ${pmc}`);
  const note = (study.note ?? "").split(":")[0].trim() || fail(`the ${pmc} source has no note`);

  const row = formRules.FORM_RULES.find((r) => r.id === STANCE_ROW_ID) ?? fail(`no ${STANCE_ROW_ID} row in src/data/formRules.ts`);
  if (row.value == null || row.value2 == null || !row.quote || !row.measureQuote || !row.source) fail(`${STANCE_ROW_ID} lacks a value, range, quote or source`);
  const src = formRules.FORM_RULE_SOURCES.find((s) => s.id === row.sourceId) ?? fail(`no source ${row.sourceId}`);

  return {
    SITE,
    TASKS_VISION_VERSION: poseBenchmark.TASKS_VISION_VERSION,
    USAGE_LOG_URL: poseBenchmark.TASKS_VISION_USAGE_LOG_URL,
    MODEL_NAME: lite.name,
    TOP: top.value,
    BOTTOM: bottom.value,
    TOP_QUOTE: top.quote,
    BOTTOM_QUOTE: bottom.quote,
    THRESHOLD_NOTE: note,
    THRESHOLD_URL: study.url,
    STANCE_MIN: row.value,
    STANCE_MAX: row.value2,
    STANCE_QUOTE: row.quote,
    STANCE_MEASURE: row.measureQuote,
    STANCE_SOURCE: row.source,
    STANCE_PROJECT: src.name,
    STANCE_LICENSE: src.license,
    STANCE_ROW: row.id,
    FORM_RULES_FETCHED_ON: formRules.FORM_RULES_FETCHED_ON,
    CONFIG: {
      bundle: poseBenchmark.TASKS_VISION_BUNDLE,
      wasm: poseBenchmark.TASKS_VISION_WASM,
      model: lite.url,
      top: top.value,
      bottom: bottom.value,
      stanceMin: row.value,
      stanceMax: row.value2,
    },
  };
}

/**
 * Fill the template. Tokens inside the leading comment are written as they
 * are (a comment cannot hold "--"); everywhere else they are HTML-escaped;
 * {{CONFIG_JSON}} is JSON safe inside a <script>. Any token left unfilled is
 * an error.
 */
export function renderRepCounter(template, values) {
  const end = template.indexOf("-->");
  if (end < 0) throw new Error("rep-counter kit: the template has no header comment");
  const fill = (text, raw) =>
    text.replace(/\{\{([A-Z_]+)\}\}/g, (m, k) => {
      if (k === "CONFIG_JSON") return JSON.stringify(values.CONFIG, null, 2).replace(/</g, "\\u003c");
      if (!(k in values)) throw new Error(`rep-counter kit: no value for {{${k}}}`);
      const v = String(values[k]);
      if (raw && /--|<!|>-/.test(v)) throw new Error(`rep-counter kit: {{${k}}} cannot go in an HTML comment: ${v}`);
      return raw ? v : escapeHtml(v);
    });
  return fill(template.slice(0, end), true) + fill(template.slice(end), false);
}

/** The URLs the page fetches when it runs: the runtime, its WASM and the model. */
export function loadedUrls(html) {
  const m = /const CONFIG = (\{[\s\S]*?\});/.exec(html);
  if (!m) throw new Error("rep-counter kit: no CONFIG in the page");
  const c = JSON.parse(m[1]);
  return [c.bundle, c.wasm, c.model];
}
