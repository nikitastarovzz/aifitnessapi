function datasets() {
  const dir = path.join(process.cwd(), "public", "datasets");
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".json") && !f.startsWith("manifest"))
    .sort()
    .map((f) => {
      const d = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")) as { name?: string; license?: string; items?: unknown };
      return Array.isArray(d.items) && d.name ? { slug: f.replace(/\.json$/, ""), name: d.name, license: d.license ?? "CC BY 4.0" } : null;
    })
    .filter((d): d is { slug: string; name: string; license: string } => d !== null);
}

let cached: AwesomeModel | null = null;

export function awesomePageModel(): AwesomeModel {
  if (cached) return cached;
  cached = awesomeModel({
    siteUrl: site.url,
    apis: API_ENTRIES,
    categoryOrder: CATEGORY_ORDER,
    categoryLabels: CATEGORY_LABELS,
    devCostLabels: DEV_COST_LABELS,
    libraries: LIBRARIES,
    libraryGroups: LIBRARY_GROUPS,
    librariesFetchedOn: LIBRARIES_FETCHED_ON,
    mcpServers: MCP_HEALTH_SERVERS,
    mcpGroups: MCP_SERVER_GROUPS,
    mcpFetchedOn: MCP_SERVERS_FETCHED_ON,
    datasets: datasets(),
    tools: ALL_TOOLS,
  });
  return cached;
}

/** The newest date the list's generated inputs were read. */
export function awesomeAsOf(): string {
  return [LIBRARIES_FETCHED_ON, MCP_SERVERS_FETCHED_ON].sort().at(-1)!;
}

export function awesomeCapsule(): string {
  return awesomeLead(awesomePageModel());
}

