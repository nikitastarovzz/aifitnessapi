import type { Metadata } from "next";
import Link from "next/link";
import Container from "@/components/Container";
import Breadcrumbs from "@/components/Breadcrumbs";
import { ATLAS_DESCRIPTION, ATLAS_H1, ATLAS_PATH, ATLAS_TITLE } from "@/lib/audienceTools";
import { ATLAS_PDF, ATLAS_SVG, atlasAsOf, atlasCapsule, atlasCategories, atlasMethodLines } from "@/lib/atlasView";
import { pageMirrorAlternates } from "@/lib/pageMirrors/alternates";
import { absoluteUrl, site } from "@/lib/site";
import { orgRef, WEBSITE_ID } from "@/lib/schema";

/**
 * /atlas — the printable Fitness API Atlas (ops/AUDIENCE-30-2026-11-05.md
 * item 30). The poster files are generated by scripts/build-atlas.mjs; this
 * page shows the SVG, links both files, and prints the poster's directory
 * section as text from the same modules.
 */

export const metadata: Metadata = {
  title: { absolute: ATLAS_TITLE },
  description: ATLAS_DESCRIPTION,
  alternates: pageMirrorAlternates(ATLAS_PATH),
  openGraph: { type: "website", title: ATLAS_TITLE, description: ATLAS_DESCRIPTION, url: ATLAS_PATH, images: ["/opengraph-image"] },
};

const linkCls = "font-medium text-brand-600 hover:text-brand-500";
const H2 = "text-2xl font-bold tracking-tight text-[var(--fg)]";

export default function AtlasPage() {
  const asOf = atlasAsOf();
  const url = absoluteUrl(ATLAS_PATH);
  const jsonLd = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "WebPage",
        "@id": `${url}#webpage`,
        url,
        name: ATLAS_TITLE,
        description: ATLAS_DESCRIPTION,
        isPartOf: { "@id": WEBSITE_ID },
        publisher: orgRef,
        dateModified: asOf,
        primaryImageOfPage: { "@id": `${url}#poster` },
      },
      {
        "@type": "ImageObject",
        "@id": `${url}#poster`,
        contentUrl: absoluteUrl(ATLAS_SVG),
        encodingFormat: "image/svg+xml",
        name: "The Fitness API Atlas",
        license: "https://creativecommons.org/licenses/by/4.0/",
        creator: orgRef,
        dateModified: asOf,
      },
      {
        "@type": "DigitalDocument",
        name: "The Fitness API Atlas (PDF, A2)",
        url: absoluteUrl(ATLAS_PDF),
        encodingFormat: "application/pdf",
        license: "https://creativecommons.org/licenses/by/4.0/",
      },
    ],
  };

  return (
    <Container className="py-14">
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }} />
      <div className="mx-auto max-w-5xl">
        <Breadcrumbs
          trail={[
            { name: "Home", path: "/" },
            { name: "Fitness API Atlas", path: ATLAS_PATH },
          ]}
        />
        <h1 className="mt-6 text-4xl font-bold leading-tight tracking-tight text-[var(--fg)] sm:text-5xl">{ATLAS_H1}</h1>
        <p id="answer" className="speakable mt-4 leading-relaxed text-[var(--muted)]">
          {atlasCapsule()}
        </p>

        <div className="mt-6 flex flex-wrap gap-3 text-sm">
          <a href={ATLAS_PDF} download className="rounded-lg bg-brand-600 px-3 py-1.5 font-semibold text-white hover:bg-brand-500" data-cta="atlas-pdf">
            Download PDF (A2)
          </a>
          <a href={ATLAS_SVG} download className="rounded-lg border border-[var(--border)] px-3 py-1.5 font-medium text-[var(--fg)] hover:border-brand-400" data-cta="atlas-svg">
            Download SVG
          </a>
          <Link href="/market-map" className="rounded-lg border border-[var(--border)] px-3 py-1.5 font-medium text-[var(--fg)] hover:border-brand-400">
            The interactive market map
          </Link>
        </div>

        <figure className="mt-8 overflow-hidden rounded-xl border border-[var(--border)] bg-white">
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={ATLAS_SVG} alt={`The Fitness API Atlas poster, data as of ${asOf}`} width={1191} height={1684} className="h-auto w-full" />
        </figure>

        <section className="mt-14">
          <h2 className={H2}>The directory on the poster, as text</h2>
          <div className="mt-4 grid gap-6 sm:grid-cols-2">
            {atlasCategories().map((c) => (
              <div key={c.id}>
                <h3 className="text-lg font-semibold text-[var(--fg)]">{c.label}</h3>
                <ul className="mt-2 space-y-1 text-sm text-[var(--muted)]">
                  {c.items.map((i) => (
                    <li key={i.id}>
                      <Link href={`/apis/${i.id}`} className={linkCls}>
                        {i.label}
                      </Link>
                      : {i.billing}
                      {i.gated ? ", approval gate" : ""}
                    </li>
                  ))}
                </ul>
              </div>
            ))}
          </div>
          <p className="mt-6 text-sm text-[var(--muted)]">
            The poster&rsquo;s other two sections are the{" "}
            <Link href="/graveyard" className={linkCls}>
              API graveyard
            </Link>{" "}
            and the{" "}
            <Link href="/changes" className={linkCls}>
              changes tracker
            </Link>
            , each entry sourced there.
          </p>
        </section>

        <section className="mt-14">
          <h2 className={H2}>How the poster is made</h2>
          <ul className="mt-4 list-disc space-y-2 pl-5 leading-relaxed text-[var(--muted)]">
            {atlasMethodLines().map((l) => (
              <li key={l}>{l}</li>
            ))}
          </ul>
          <p className="mt-4 text-sm text-[var(--muted)]">
            Free to print and share under CC BY 4.0: credit {site.name} and link {url}.
          </p>
        </section>
      </div>
    </Container>
  );
}
