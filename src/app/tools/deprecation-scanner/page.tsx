import type { Metadata } from "next";
import Link from "next/link";
import Container from "@/components/Container";
import Breadcrumbs from "@/components/Breadcrumbs";
import ClusterHero from "@/components/ClusterHero";
import MoreTools from "@/components/tools/MoreTools";
import ToolNextStep from "@/components/ToolNextStep";
import DeprecationScanner from "@/components/tools/DeprecationScanner";
import { pageMirrorAlternates } from "@/lib/pageMirrors/alternates";
import { toolGraph } from "@/lib/schema";
import { site } from "@/lib/site";
import {
  DS_ACTION_URL,
  DS_BUNDLE,
  DS_DESCRIPTION,
  DS_H1,
  DS_HOW,
  DS_PATH,
  DS_TITLE,
  DS_UPDATED,
  dsActionText,
  dsActionYaml,
  dsCapsule,
  dsScannedEntries,
} from "@/lib/deprecationScannerText";

/**
 * /tools/deprecation-scanner (ops/VIRAL-20-2026-11-06.md item 14), and the
 * usage of the GitHub Action that runs the same rules (item 15). The rules are
 * src/data/deprecationRules.json, generated by scripts/build-deprecation-rules.mjs
 * from the graveyard, the Fitbit endpoint map, the libraries dataset and
 * src/data/deprecationSignatures.ts; qa's DEPRECATION-RULES-STALE holds the
 * Action's copy to it.
 */

export const metadata: Metadata = {
  title: DS_TITLE,
  description: DS_DESCRIPTION,
  alternates: pageMirrorAlternates(DS_PATH),
  openGraph: {
    type: "website",
    title: DS_TITLE,
    description: "Find Fitbit Web API, Google Fit and other retired fitness API calls in your code, with each replacement. In the browser, or in CI as a GitHub Action.",
    url: DS_PATH,
    images: ["/opengraph-image"],
  },
};

const linkCls = "font-medium text-brand-600 hover:text-brand-500";
const code = "font-mono text-sm";

function rulesFor(entry: string) {
  return DS_BUNDLE.rules.filter((r) => r.entry === entry);
}

export default function DeprecationScannerPage() {
  const jsonLd = toolGraph({
    path: DS_PATH,
    name: DS_TITLE,
    alternativeHeadline: "Scan code and manifests for shut-down and deprecated fitness API calls",
    description: DS_DESCRIPTION,
    dateModified: DS_UPDATED,
    webPage: { lastReviewed: DS_UPDATED },
  });
  const entries = dsScannedEntries();
  const fitbitRules = DS_BUNDLE.counts.fitbitEndpointRules;

  return (
    <Container className="py-14">
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }} />
      <div className="mx-auto max-w-5xl">
        <Breadcrumbs
          trail={[
            { name: "Home", path: "/" },
            { name: "Tools", path: "/tools" },
            { name: "Deprecation scanner", path: DS_PATH },
          ]}
        />
        <ClusterHero label="Free Tool" seed={14} />

        <h1 className="text-4xl font-bold leading-tight tracking-tight text-[var(--fg)] sm:text-5xl">{DS_H1}</h1>

        <p id="answer" className="speakable mt-4 leading-relaxed text-[var(--muted)]">
          {dsCapsule()}
        </p>

        <section data-tool="deprecation-scanner" aria-label="Deprecation scanner">
          <DeprecationScanner />
        </section>

        <section className="mt-14" id="github-action">
          <h2 className="text-2xl font-bold tracking-tight text-[var(--fg)]">Run the same scan in CI</h2>
          <p className="mt-3 leading-relaxed text-[var(--muted)]">
            The rules above also ship as a GitHub Action in{" "}
            <a href={DS_ACTION_URL} className={linkCls} rel="noopener">
              this site’s repository
            </a>
            . Add this workflow to <code className={code}>.github/workflows/</code>:
          </p>
          <pre className="mt-4 overflow-x-auto rounded-2xl border border-[var(--border)] bg-[var(--surface)] p-4 text-sm leading-relaxed text-[var(--fg)]">
            <code>{dsActionYaml()}</code>
          </pre>
          <p className="mt-3 text-sm leading-relaxed text-[var(--muted)]">{dsActionText()}</p>
          <p className="mt-3 text-sm leading-relaxed text-[var(--muted)]">
            The Action and this page run one rule file and one engine. Both are written by a generator from this site’s data, and the build fails when the
            Action’s copy differs, so the two cannot disagree. A workflow in the repository runs the Action on its own test fixtures on every change.
          </p>
        </section>

        <section className="mt-14">
          <h2 className="text-2xl font-bold tracking-tight text-[var(--fg)]">What it looks for</h2>
          <p className="mt-3 leading-relaxed text-[var(--muted)]">
            {DS_BUNDLE.counts.rules} patterns over {entries.length} entries of{" "}
            <Link href="/graveyard" className={linkCls}>
              the Fitness API Graveyard
            </Link>
            . Status and date are the graveyard’s, which keeps each vendor’s precision: a year stays a year. Each Fitbit hit links its row on{" "}
            <Link href="/tools/fitbit-to-google-health" className={linkCls}>
              the Fitbit to Google Health API map
            </Link>
            .
          </p>
          <div className="mt-4 overflow-x-auto">
            <table className="w-full min-w-[640px] text-left text-sm">
              <thead className="text-[var(--muted)]">
                <tr>
                  <th className="py-2 pr-3 font-semibold">API or SDK</th>
                  <th className="py-2 pr-3 font-semibold">Status</th>
                  <th className="py-2 pr-3 font-semibold">What is matched</th>
                  <th className="py-2 font-semibold">Replacement the vendor names</th>
                </tr>
              </thead>
              <tbody>
                {entries.map((e) => {
                  const rs = rulesFor(e.id);
                  const shown = e.id === "fitbit-web-api" ? [] : rs.slice(0, 6);
                  return (
                    <tr key={e.id} id={`entry-${e.id}`} className="border-t border-[var(--border)] align-top">
                      <td className="py-3 pr-3">
                        <Link href={e.graveyard} className={linkCls}>
                          {e.name}
                        </Link>
                        <span className="block text-xs text-[var(--muted)]">{e.vendor}</span>
                      </td>
                      <td className="py-3 pr-3 text-[var(--muted)]">
                        {e.statusLabel}. {e.end ? `${e.endLabel}: ${e.endText}` : e.endLabel}
                      </td>
                      <td className="py-3 pr-3 text-[var(--muted)]">
                        {e.id === "fitbit-web-api" ? (
                          <>
                            Every endpoint path in Fitbit’s reference ({fitbitRules} paths for {DS_BUNDLE.counts.fitbitEndpoints} endpoints), its OAuth endpoints on a
                            fitbit.com host, the <code className={code}>api.fitbit.com</code> host
                            {rs.filter((r) => r.id.startsWith("library:")).map((r) => (
                              <span key={r.id}>, and {r.label}</span>
                            ))}
                            .
                          </>
                        ) : (
                          <ul className="space-y-1">
                            {shown.map((r) => (
                              <li key={r.id}>{r.label}</li>
                            ))}
                          </ul>
                        )}
                      </td>
                      <td className="py-3 text-[var(--muted)]">
                        {e.replacedBy.length
                          ? e.replacedBy.map((x, i) => (
                              <span key={x.label}>
                                {i > 0 ? "; " : ""}
                                {x.href ? (
                                  <Link href={x.href} className={linkCls}>
                                    {x.label}
                                  </Link>
                                ) : (
                                  x.label
                                )}
                              </span>
                            ))
                          : "None"}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
          {DS_BUNDLE.notScanned.length > 0 && (
            <>
              <h3 className="mt-6 text-lg font-semibold text-[var(--fg)]">What it does not look for</h3>
              <ul className="mt-2 list-disc space-y-1 pl-5 text-sm text-[var(--muted)]">
                {DS_BUNDLE.notScanned.map((n) => (
                  <li key={`${n.entry}${n.reason}`}>
                    <Link href={`/graveyard#${n.entry}`} className={linkCls}>
                      {n.name}
                    </Link>
                    : {n.reason}
                  </li>
                ))}
              </ul>
            </>
          )}
        </section>

        <section className="mt-14">
          <h2 className="text-2xl font-bold tracking-tight text-[var(--fg)]">How a hit is decided</h2>
          <ol className="mt-4 list-decimal space-y-3 pl-5 leading-relaxed text-[var(--muted)]">
            {DS_HOW.map((h) => (
              <li key={h.title}>
                <strong className="text-[var(--fg)]">{h.title}</strong> {h.text}
              </li>
            ))}
          </ol>
        </section>

        <details className="mt-14 rounded-2xl border border-[var(--border)] bg-[var(--surface)] p-5">
          <summary className="cursor-pointer font-semibold text-[var(--fg)]">Sources and what this cannot tell you</summary>
          <div className="mt-3 space-y-3 text-sm leading-relaxed text-[var(--muted)]">
            <p>
              Built {DS_UPDATED} from: the graveyard (entries read up to {DS_BUNDLE.inputs.graveyard}), Fitbit’s Web API reference (read{" "}
              {DS_BUNDLE.inputs.fitbitWebApi} through source snapshots), Google’s migration tables (read {DS_BUNDLE.inputs.googleHealthApi}), the library
              registry data (read {DS_BUNDLE.inputs.libraries}) and the pages behind the other patterns (read {DS_BUNDLE.inputs.signatures}; hosts blocked
              from where this site is built were read on a GitHub runner, and old API docs through Internet Archive captures). Each quoted passage is in an
              evidence file that a weekly workflow re-checks against the live page.
            </p>
            <p>
              A text scan cannot see a URL assembled across files, a call made inside a dependency, or an SDK pulled in by another SDK. A clean result
              means none of these patterns appear, not that nothing in the app depends on a retired API. Pasted text and opened files stay in this tab.
            </p>
          </div>
        </details>

        <p className="mt-8 text-sm text-[var(--muted)]">
          A free tool from {site.name}. More at{" "}
          <Link href="/tools" className={linkCls}>
            free tools for health-app builders
          </Link>
          .
        </p>
        <MoreTools path={DS_PATH} />
        <ToolNextStep path={DS_PATH} />
      </div>
    </Container>
  );
}
