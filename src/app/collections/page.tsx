import type { Metadata } from "next";
import Link from "next/link";
import Container from "@/components/Container";
import Breadcrumbs from "@/components/Breadcrumbs";
import {
  COLLECTIONS_DESCRIPTION,
  COLLECTIONS_H1,
  COLLECTIONS_IMPORT,
  COLLECTIONS_METHOD,
  COLLECTIONS_PATH,
  COLLECTIONS_SOURCES,
  COLLECTIONS_TITLE,
  collectionIndex,
  collectionsAsOf,
  collectionsCapsule,
  kb,
} from "@/lib/kitPages";
import { pageMirrorAlternates } from "@/lib/pageMirrors/alternates";
import { absoluteUrl, site } from "@/lib/site";
import { orgRef, WEBSITE_ID } from "@/lib/schema";

/**
 * /collections — Postman and Bruno collections (ops/VIRAL-20-2026-11-06.md
 * item 12). The files are generated by scripts/build-collections.mjs; this
 * page lists public/collections/index.json, which that script writes.
 */

export const metadata: Metadata = {
  title: { absolute: COLLECTIONS_TITLE },
  description: COLLECTIONS_DESCRIPTION,
  alternates: pageMirrorAlternates(COLLECTIONS_PATH),
  openGraph: { type: "website", title: COLLECTIONS_TITLE, description: COLLECTIONS_DESCRIPTION, url: COLLECTIONS_PATH },
};

const linkCls = "font-medium text-brand-600 hover:text-brand-500";
const H2 = "text-2xl font-bold tracking-tight text-[var(--fg)]";
const btn = "rounded-lg border border-[var(--border)] px-3 py-1.5 text-sm font-medium text-[var(--fg)] hover:border-brand-400";

export default function CollectionsPage() {
  const list = collectionIndex();
  const url = absoluteUrl(COLLECTIONS_PATH);
  const jsonLd = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "CollectionPage",
        "@id": `${url}#webpage`,
        url,
        name: COLLECTIONS_TITLE,
        description: COLLECTIONS_DESCRIPTION,
        isPartOf: { "@id": WEBSITE_ID },
        publisher: orgRef,
        dateModified: collectionsAsOf(),
      },
      ...list.map((c) => ({
        "@type": "DigitalDocument",
        name: `${c.name} Postman collection`,
        url: absoluteUrl(c.postman),
        encodingFormat: "application/json",
        license: "https://creativecommons.org/licenses/by/4.0/",
      })),
    ],
  };

  return (
    <Container className="py-14">
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }} />
      <div className="mx-auto max-w-4xl">
        <Breadcrumbs
          trail={[
            { name: "Home", path: "/" },
            { name: "API collections", path: COLLECTIONS_PATH },
          ]}
        />
        <h1 className="mt-6 text-4xl font-bold leading-tight tracking-tight text-[var(--fg)] sm:text-5xl">{COLLECTIONS_H1}</h1>
        <p id="answer" className="speakable mt-4 leading-relaxed text-[var(--muted)]">
          {collectionsCapsule()}
        </p>

        <section className="mt-12">
          <h2 className={H2}>Download a collection</h2>
          <ul className="mt-6 space-y-4">
            {list.map((c) => (
              <li key={c.id} id={c.id} className="scroll-mt-24 rounded-xl border border-[var(--border)] p-5" data-collection={c.id}>
                <h3 className="text-lg font-semibold text-[var(--fg)]">{c.name}</h3>
                <ul className="mt-2 space-y-1 text-sm text-[var(--muted)]">
                  {c.folders.map((f) => (
                    <li key={f.name}>
                      <span className="font-medium text-[var(--fg)]">{f.name}:</span> {f.requests.join("; ")}
                    </li>
                  ))}
                  <li>
                    <span className="font-medium text-[var(--fg)]">Variables:</span> {c.variables.map((v) => `{{${v}}}`).join(", ")}
                  </li>
                </ul>
                <div className="mt-3 flex flex-wrap gap-2">
                  <a href={c.postman} download className={btn} data-cta={`collection-postman-${c.id}`}>
                    Postman v2.1 ({kb(c.postmanBytes)})
                  </a>
                  <a href={c.bruno} download className={btn} data-cta={`collection-bruno-${c.id}`}>
                    Bruno folder, .zip ({kb(c.brunoBytes)})
                  </a>
                </div>
              </li>
            ))}
          </ul>
        </section>

        <section className="mt-14">
          <h2 className={H2}>Import into Postman</h2>
          <ol className="mt-4 list-decimal space-y-2 pl-5 leading-relaxed text-[var(--muted)]">
            {COLLECTIONS_IMPORT.postman.map((l) => (
              <li key={l}>{l}</li>
            ))}
          </ol>
          <h2 className={`${H2} mt-10`}>Open in Bruno</h2>
          <ol className="mt-4 list-decimal space-y-2 pl-5 leading-relaxed text-[var(--muted)]">
            {COLLECTIONS_IMPORT.bruno.map((l) => (
              <li key={l}>{l}</li>
            ))}
          </ol>
          <p className="mt-4 text-sm text-[var(--muted)]">
            Steps from{" "}
            {COLLECTIONS_SOURCES.map((s, i) => (
              <span key={s.url}>
                {i ? ", " : ""}
                <a href={s.url} className={linkCls}>
                  {s.label}
                </a>
              </span>
            ))}
            , read 2026-11-06.
          </p>
        </section>

        <section className="mt-14">
          <h2 className={H2}>How the collections are made</h2>
          <ul className="mt-4 list-disc space-y-2 pl-5 leading-relaxed text-[var(--muted)]">
            {COLLECTIONS_METHOD.map((l) => (
              <li key={l}>{l}</li>
            ))}
          </ul>
          <p className="mt-4 text-sm text-[var(--muted)]">
            The facts behind each request, with the vendor sentence they rest on, are on the{" "}
            <Link href="/tools/oauth-playground" className={linkCls}>
              OAuth playground
            </Link>{" "}
            and in the{" "}
            <Link href="/webhooks" className={linkCls}>
              webhook payload library
            </Link>
            . Free to share under CC BY 4.0: credit {site.name} and link {url}.
          </p>
        </section>
      </div>
    </Container>
  );
}
