import type { Metadata } from "next";
import { pageMirrorAlternates } from "@/lib/pageMirrors/alternates";
import Link from "next/link";
import Container from "@/components/Container";
import Breadcrumbs from "@/components/Breadcrumbs";
import AnswerCapsule from "@/components/AnswerCapsule";
import { absoluteUrl, site } from "@/lib/site";
import { orgNamed } from "@/lib/schema";
import { datasetBibtex } from "@/lib/cite";
import { COUNT_ENTRIES, DATASETS_UPDATED as UPDATED, LICENSE_URL, LOADED, citeAs, fmtUpdated } from "@/lib/datasetsPage";

/**
 * The open-data index. Every dataset listed here is generated by
 * `npm run datasets` (scripts/build-datasets.mjs) from the same data modules
 * that render the pages, except fitness-apis-2026.* which predates the
 * generator. Counts, field lists, names and versions on this page are read
 * from the generated JSON at build time — never typed by hand, so the page
 * cannot claim a row count the file does not have.
 */

const PAGE_PATH = "/datasets";

/** The dataset count for the meta description, read off ENTRIES so the
 *  number can never fall behind the list. Digits, not a word: "Eleven" pushed
 *  the description past the 155-character cap when the eleventh dataset
 *  landed, and digits stay two characters wide up to 99. */
const COUNT = String(COUNT_ENTRIES);

export const metadata: Metadata = {
  title: { absolute: "Open Datasets: Fitness & Health API Data (CC BY 4.0)" },
  description:
    `${COUNT} open CC BY 4.0 datasets: HealthKit, Health Connect, Wear OS and Google Health API types, pose keypoints, the API directory, changes, glossary.`,
  alternates: pageMirrorAlternates(PAGE_PATH),
  openGraph: {
    type: "website",
    title: "Open Datasets — Fitness & Health API Data",
    description:
      `${COUNT} CC BY 4.0 datasets in JSON and CSV: HealthKit, Health Connect, Wear OS and Google Health API types, pose keypoint maps, the dated changes record, the glossary and the API directory.`,
    url: PAGE_PATH,
    images: ["/opengraph-image"],
  },
};

export default function DatasetsPage() {
  const url = absoluteUrl(PAGE_PATH);
  const totalRows = LOADED.reduce((n, l) => n + l.file.rows, 0);
  const bySlug = Object.fromEntries(LOADED.map((l) => [l.entry.slug, l.file.rows]));
  // Read off the files rather than typed here, so the header line cannot claim
  // a version the downloads do not carry.
  const versions = [...new Set(LOADED.map((l) => l.file.version))].sort();
  const versionLabel = versions.length === 1 ? `version ${versions[0]}` : `versions ${versions.join(", ")}`;

  const catalogJsonLd = {
    "@context": "https://schema.org",
    "@type": "DataCatalog",
    name: "AIFitnessAPI Open Datasets",
    description:
      "Open, versioned datasets about fitness and health APIs, published in JSON and CSV under CC BY 4.0 with a per-row link to the page carrying the sourced claim.",
    url,
    license: LICENSE_URL,
    creator: orgNamed(),
    publisher: orgNamed(),
    isAccessibleForFree: true,
    dataset: LOADED.map(({ entry, file }) => ({
      "@type": "Dataset",
      name: file.name,
      description: entry.blurb,
      url: absoluteUrl(entry.presentedBy.href),
      version: file.version,
      license: LICENSE_URL,
      creator: orgNamed(),
      publisher: orgNamed(),
      isAccessibleForFree: true,
      keywords: entry.keywords,
      variableMeasured: file.columns,
      distribution: [
        {
          "@type": "DataDownload",
          encodingFormat: "application/json",
          contentUrl: absoluteUrl(`/datasets/${entry.slug}.json`),
        },
        {
          "@type": "DataDownload",
          encodingFormat: "text/csv",
          contentUrl: absoluteUrl(`/datasets/${entry.slug}.csv`),
        },
      ],
    })),
  };

  return (
    <Container className="py-14">
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(catalogJsonLd) }}
      />

      <div className="mx-auto max-w-3xl">
        <Breadcrumbs trail={[{ name: "Home", path: "/" }, { name: "Open Datasets", path: PAGE_PATH }]} />

        <h1 className="text-4xl font-bold leading-tight tracking-tight text-[var(--fg)] sm:text-5xl">
          Open Datasets
        </h1>
        <p className="mt-3 text-sm text-[var(--muted)]">
          {LOADED.length} datasets &middot; {totalRows} rows &middot; {versionLabel}{" "}&middot; CC BY 4.0 &middot;
          updated {fmtUpdated(UPDATED)}
        </p>

        <AnswerCapsule>
          AIFitnessAPI publishes {LOADED.length} open datasets about fitness and health APIs, each in
          both JSON and CSV, each versioned 2026.1 and licensed CC BY 4.0 with attribution as the only
          condition (where a dataset restates another publisher’s facts, its note says what the license
          covers): the access-structure survey of{" "}
          {bySlug["fitness-apis-2026"]}{" "}APIs, SDKs and models; the HealthKit &harr; Health Connect
          identifier matrix covering {bySlug["health-data-type-matrix-2026"]} health metrics; the dated
          record of {bySlug["fitness-api-changes-2026"]} ecosystem changes, each graded for evidence
          strength; and the glossary of {bySlug["fitness-api-glossary-2026"]} defined terms. Three rules
          hold across all of them — there is not one dollar figure anywhere by design, a field we could
          not verify is null rather than guessed, and editions are versioned rather than overwritten, so
          a citation to 2026.1 keeps pointing at what 2026.1 said.
        </AnswerCapsule>

        <div className="mt-12 space-y-8">
          {LOADED.map(({ entry, file }) => (
            <section
              key={entry.slug}
              id={entry.slug}
              className="scroll-mt-24 rounded-2xl border border-[var(--border)] p-6"
            >
              <h2 className="text-2xl font-bold tracking-tight text-[var(--fg)]">{file.name}</h2>
              <p className="mt-1 text-sm text-[var(--muted)]">
                {file.rows} rows ({entry.unit}) &middot; {file.columns.length} columns &middot; version{" "}
                {file.version} &middot; {file.license}
              </p>

              <p className="mt-4 text-[var(--fg)]">{entry.blurb}</p>
              <p className="mt-3 text-sm text-[var(--muted)]">{entry.caveat}</p>

              <div className="mt-5 flex flex-wrap items-center gap-3 text-sm">
                <a
                  href={`/datasets/${entry.slug}.json`}
                  className="rounded-lg border border-brand-400/50 bg-brand-500/10 px-3 py-1.5 font-semibold text-[var(--fg)] hover:border-brand-400"
                >
                  {entry.slug}.json
                </a>
                <a
                  href={`/datasets/${entry.slug}.csv`}
                  className="rounded-lg border border-[var(--border)] px-3 py-1.5 font-semibold text-[var(--fg)] hover:border-brand-400"
                >
                  {entry.slug}.csv
                </a>
                <Link href={entry.presentedBy.href} className="text-brand-600 hover:text-brand-500">
                  Read it as a page: {entry.presentedBy.label}{" "}&rarr;
                </Link>
              </div>

              <dl className="mt-5 grid gap-2 text-sm">
                <div className="flex min-w-0 flex-wrap gap-x-2">
                  <dt className="font-semibold text-[var(--fg)]">License:</dt>
                  <dd className="min-w-0 break-words text-[var(--muted)]">
                    <a
                      href={LICENSE_URL}
                      rel="license noopener"
                      className="text-brand-600 hover:text-brand-500"
                    >
                      Creative Commons Attribution 4.0
                    </a>{" "}
                    — reuse and redistribute freely, including commercially, with attribution.
                  </dd>
                </div>
                <div className="flex min-w-0 flex-wrap gap-x-2">
                  <dt className="font-semibold text-[var(--fg)]">Cite as:</dt>
                  <dd className="min-w-0 break-words text-[var(--muted)]">{citeAs(file, entry.slug)}</dd>
                </div>
                <div className="flex min-w-0 flex-wrap gap-x-2">
                  <dt className="font-semibold text-[var(--fg)]">Dataset card:</dt>
                  <dd className="min-w-0 break-words text-[var(--muted)]">
                    <a href={`/datasets/${entry.slug}.md`} className="text-brand-600 hover:text-brand-500" data-dataset-card={entry.slug}>
                      {entry.slug}.md
                    </a>{" "}
                    — fields, sources, license and update cadence, generated with the files
                  </dd>
                </div>
                <div className="flex min-w-0 flex-wrap gap-x-2">
                  <dt className="font-semibold text-[var(--fg)]">Columns:</dt>
                  <dd className="min-w-0 break-words font-mono text-xs text-[var(--muted)]">
                    {file.columns.join(", ")}
                  </dd>
                </div>
              </dl>

              <details className="mt-4 text-sm">
                <summary className="cursor-pointer font-semibold text-[var(--fg)]">BibTeX</summary>
                <pre className="mt-2 overflow-x-auto rounded-lg border border-[var(--border)] bg-[var(--surface)] p-3 text-xs" data-bibtex={entry.slug}>
                  {datasetBibtex({
                    slug: entry.slug,
                    name: file.name,
                    version: file.version,
                    url: absoluteUrl(`/datasets/${entry.slug}.json`),
                    license: file.license,
                  })}
                </pre>
              </details>
            </section>
          ))}
        </div>

        <section id="cite" className="mt-12 scroll-mt-24 rounded-2xl border border-[var(--border)] p-6">
          <h2 className="text-2xl font-bold tracking-tight text-[var(--fg)]">How to cite the datasets</h2>
          <p className="mt-3 text-sm text-[var(--muted)]">
            Each dataset above carries its own citation string and BibTeX entry. For the collection as a whole, the
            repository&rsquo;s{" "}
            <a href={`${site.social.github}/blob/main/CITATION.cff`} className="text-brand-600 hover:text-brand-500">
              CITATION.cff
            </a>{" "}
            is generated with the files and lists every dataset, so GitHub&rsquo;s &ldquo;Cite this repository&rdquo;
            button and reference managers that read CFF give the same answer as this page.
          </p>
          <pre className="mt-4 overflow-x-auto rounded-lg border border-[var(--border)] bg-[var(--surface)] p-3 text-xs" data-bibtex="collection">
            {datasetBibtex({
              slug: "datasets",
              name: "AIFitnessAPI Open Datasets",
              version: versions.at(-1) as string,
              url: url,
              license: "CC BY 4.0",
            })}
          </pre>
          <p className="mt-3 text-sm text-[var(--muted)]">
            Citable counts about the datasets and the site, each with its source file and date, are on{" "}
            <Link href="/press" className="text-brand-600 hover:text-brand-500">
              the press page
            </Link>
            .
          </p>
        </section>

        <section className="mt-14 prose prose-neutral max-w-none dark:prose-invert prose-a:text-brand-600 hover:prose-a:text-brand-500">
          <h2>The rules these files follow</h2>
          <p>
            <strong>No dollar figures, by design.</strong> There is not one monetary value in any of
            these datasets. Most serious tiers in this market are contact-sales, published figures move
            within a quarter, and a stale number damages a citable source more than a missing one. What
            we publish instead is structure: how a vendor bills, what gates a launch, what the end user
            must already own. The <Link href="/cost-planner">cost planner</Link> works the same way and
            likewise refuses to produce a total.
          </p>
          <p>
            <strong>A null means we could not verify it.</strong> It never means zero and it is never a
            guess. If a field is empty in the CSV, the corresponding page on this site carries no
            sentence documenting it — that is the whole claim. Judgment calls stay out of the data
            entirely rather than being laundered into a column.
          </p>
          <p>
            <strong>Versioned, not overwritten.</strong> Every file is pinned at version 2026.1. The
            next edition re-verifies each row and ships under a new version rather than editing these
            in place, so a citation to 2026.1 keeps pointing at what 2026.1 actually said.
          </p>
          <p>
            <strong>Every row traces to a page.</strong> Each dataset carries a link column pointing at
            the page on this site that states the claim in prose, with its own sourcing and review
            date. Nothing here asserts more than its source page does. How we verify is written up in{" "}
            <Link href="/methodology">our methodology</Link>.
          </p>
          <p>
            <strong>Generated, not typed.</strong> Every file is built by{" "}
            <code>scripts/build-datasets.mjs</code> from the same data modules that render the pages, so a dataset cannot drift from the page it came from. The
            counts, field lists and versions shown above are read out of the published JSON when this
            page is built, which is why they cannot disagree with the downloads.
          </p>

          <h2>Using them</h2>
          <p>
            The JSON files share one envelope: <code>name</code>, <code>version</code>,{" "}
            <code>publisher</code>, <code>license</code>, <code>methodology</code>,{" "}
            <code>generatedFrom</code>, a <code>fields</code> dictionary describing the columns, a{" "}
            <code>stats</code> block, and the <code>items</code> array. The CSVs carry the same rows
            and columns, RFC 4180 quoted, with an empty field wherever the JSON has null.
          </p>
          <p>
            Attribution is the only condition. A link to{" "}
            <Link href="/datasets">aifitnessapi.com/datasets</Link> alongside the citation string above
            satisfies it. If you find an error in a row, the page it links is the place it will be
            corrected first.
          </p>
          <p>
            The same rows are also served one at a time, as a read-only JSON API with an OpenAPI 3.1
            document and as tools on a hosted MCP server for AI assistants. No key is needed for either;
            see <Link href="/developers">the developer API and MCP server</Link>.
          </p>
        </section>

        <p className="mt-10 text-sm text-[var(--muted)]">
          Published by {site.name}. Independent and not sponsored — one row of the access-structure
          survey covers KinesteX, the company that funds this site, recorded on the same terms as every
          competitor.
        </p>
      </div>
    </Container>
  );
}
